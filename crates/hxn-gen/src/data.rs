//! Plain data: the library's `#[hxn::data]` structs and enums, and how their
//! values are passed across the boundary.
//!
//! A C-like enum is passed as its integer value. A composite value is
//! serialized to bytes in the format `hxn_abi::wire` describes: each side has
//! generated code that writes the value's parts in order and reads them back.
//! The Haxe side is plain Haxe, the same file for every runtime.

use crate::haxe::File;
use crate::model::{Case, Data, Enumeration, Library, Number, Record, Tagged};
use crate::names::{camel, exception_class, snake, wire_class};

const HEADER: &str = "// Generated by hxn-gen from the library's source. Do not edit.\n";

fn docs(lines: &[String], indent: &str) -> String {
    match lines {
        [] => String::new(),
        [line] => format!("{indent}/** {line} **/\n"),
        lines => {
            let mut out = format!("{indent}/**\n");
            for line in lines {
                out.push_str(&format!("{indent}\t{line}\n"));
            }
            out.push_str(&format!("{indent}**/\n"));
            out
        }
    }
}

/// The adapter's function that deserializes a record, or converts an integer
/// to an enum: `hxn_read_options`.
pub fn reader(name: &str) -> String {
    format!("hxn_read_{}", snake(name))
}

/// The adapter's function that serializes a record, or returns an enum's
/// integer value.
pub fn writer(name: &str) -> String {
    format!("hxn_write_{}", snake(name))
}

// The minimum encoded size of a value, used to bound a list's item count.
fn least(data: &Data) -> usize {
    match data {
        Data::Bool | Data::Option(_) | Data::Record(_) => 1,
        Data::I64 | Data::F64 | Data::Number(Number::U64 | Number::F32) => 8,
        Data::Boxed(of) => least(of),
        Data::Tuple(parts) => parts.iter().map(least).sum(),
        _ => 4,
    }
}

/// The Rust type of `data`.
pub fn rust_type(data: &Data) -> String {
    match data {
        Data::Bool => String::from("bool"),
        Data::I32 => String::from("i32"),
        Data::I64 => String::from("i64"),
        Data::F64 => String::from("f64"),
        Data::Number(number) => number.name().to_owned(),
        Data::Text => String::from("String"),
        Data::Bytes => String::from("Vec<u8>"),
        Data::Enum(name) | Data::Record(name) | Data::Tagged(name) => name.clone(),
        Data::Option(of) => format!("Option<{}>", rust_type(of)),
        Data::List(of) => format!("Vec<{}>", rust_type(of)),
        Data::Tuple(parts) => format!(
            "({},)",
            parts.iter().map(rust_type).collect::<Vec<_>>().join(", ")
        ),
        Data::Set { of, sorted } => format!(
            "std::collections::{}<{}>",
            if *sorted { "BTreeSet" } else { "HashSet" },
            rust_type(of)
        ),
        Data::Boxed(of) => format!("Box<{}>", rust_type(of)),
        Data::Map { key, value, sorted } => format!(
            "std::collections::{}<{}, {}>",
            if *sorted { "BTreeMap" } else { "HashMap" },
            rust_type(key),
            rust_type(value)
        ),
    }
}

/// The target type of a reference to it: a list is borrowed as a slice.
pub fn rust_lent(data: &Data) -> String {
    match data {
        Data::List(of) => format!("[{}]", rust_type(of)),
        other => rust_type(other),
    }
}

/// The Rust expression that deserializes `data` from `input`. It propagates
/// a `Fault` with `?`.
pub fn rust_read(data: &Data) -> String {
    match data {
        Data::Bool => String::from("input.bool()?"),
        Data::I32 => String::from("input.i32()?"),
        Data::I64 => String::from("input.i64()?"),
        Data::F64 => String::from("input.f64()?"),
        Data::Number(Number::U32) => String::from("input.i32()? as u32"),
        Data::Number(Number::U64) => String::from("input.i64()? as u64"),
        Data::Number(Number::F32) => String::from("input.f64()? as f32"),
        Data::Number(number) => format!(
            "{}::try_from(input.i32()?).map_err(|_| Fault::Range)?",
            number.name()
        ),
        Data::Text => String::from("input.text()?"),
        Data::Bytes => String::from("input.bytes()?"),
        Data::Enum(name) => format!("{}(input.i32()?)?", reader(name)),
        Data::Record(name) | Data::Tagged(name) => format!("{}(input)?", reader(name)),
        Data::Boxed(of) => format!("Box::new({})", rust_read(of)),
        Data::Tuple(parts) => format!(
            "({},)",
            parts.iter().map(rust_read).collect::<Vec<_>>().join(", ")
        ),
        Data::Map { key, value, .. } => format!(
            "{{ let count = input.items({})?; let mut items: {} = Default::default(); for _ in 0..count {{ let key = {}; let value = {}; items.insert(key, value); }} items }}",
            least(key) + least(value),
            rust_type(data),
            rust_read(key),
            rust_read(value)
        ),
        Data::Option(of) => format!(
            "if input.bool()? {{ Some({}) }} else {{ None }}",
            rust_read(of)
        ),
        Data::List(of) => format!(
            "{{ let count = input.items({})?; let mut items = Vec::with_capacity(count); for _ in 0..count {{ items.push({}); }} items }}",
            least(of),
            rust_read(of)
        ),
        Data::Set { of, .. } => format!(
            "{{ let count = input.items({})?; let mut items: {} = Default::default(); for _ in 0..count {{ items.insert({}); }} items }}",
            least(of),
            rust_type(data),
            rust_read(of)
        ),
    }
}

/// The Rust statements that serialize `data` into `out`, given an expression
/// for a reference to the value.
pub fn rust_write(data: &Data, value: &str) -> String {
    let wire = "hxn_abi::wire";
    match data {
        Data::Bool => format!("{wire}::bool(out, *{value});"),
        Data::I32 => format!("{wire}::i32(out, *{value});"),
        Data::I64 => format!("{wire}::i64(out, *{value});"),
        Data::F64 => format!("{wire}::f64(out, *{value});"),
        Data::Number(Number::U32) => format!("{wire}::i32(out, *{value} as i32);"),
        Data::Number(Number::U64) => format!("{wire}::i64(out, *{value} as i64);"),
        Data::Number(Number::F32) => format!("{wire}::f64(out, f64::from(*{value}));"),
        Data::Number(Number::Isize | Number::Usize) => {
            format!("{wire}::i32(out, i32::try_from(*{value}).map_err(|_| Fault::Range)?);")
        }
        Data::Number(_) => format!("{wire}::i32(out, i32::from(*{value}));"),
        Data::Text => format!("{wire}::text(out, {value})?;"),
        Data::Bytes => format!("{wire}::bytes(out, {value})?;"),
        Data::Enum(name) => format!("{wire}::i32(out, {}({value}));", writer(name)),
        Data::Record(name) | Data::Tagged(name) => format!("{}({value}, out)?;", writer(name)),
        // Bound to a name first, so that what is written is a reference to
        // the inner value, not to the box.
        Data::Boxed(of) => format!("{{ let inner = &**{value}; {} }}", rust_write(of, "inner")),
        Data::Tuple(parts) => {
            let written = parts
                .iter()
                .enumerate()
                .map(|(index, part)| {
                    format!(
                        "{{ let part = &tuple.{index}; {} }}",
                        rust_write(part, "part")
                    )
                })
                .collect::<Vec<_>>()
                .join(" ");
            format!("{{ let tuple = {value}; {written} }}")
        }
        Data::Map {
            key, value: held, ..
        } => format!(
            "{{ let items = {value}; {wire}::count(out, items.len())?; for (key, value) in items.iter() {{ {} {} }} }}",
            rust_write(key, "key"),
            rust_write(held, "value")
        ),
        Data::Option(of) => format!(
            "match {value} {{ Some(value) => {{ {wire}::bool(out, true); {} }} None => {wire}::bool(out, false), }}",
            rust_write(of, "value")
        ),
        // Bound to a name first: `value` may be `&a.b`, and a method call
        // would bind tighter than the `&`.
        Data::List(of) | Data::Set { of, .. } => format!(
            "{{ let items = {value}; {wire}::count(out, items.len())?; for item in items.iter() {{ {} }} }}",
            rust_write(of, "item")
        ),
    }
}

/// A parameter's value, deserialized from all of `bytes`: the right-hand side
/// of the statement.
pub fn rust_decoded(data: &Data, bytes: &str) -> String {
    format!(
        "{{ let mut reader = hxn_abi::wire::Reader::new({bytes}); let input = &mut reader; let value = {}; input.end()?; value }}",
        rust_read(data)
    )
}

/// The serialized bytes of a return value, given the call that produces it.
pub fn rust_encoded(data: &Data, call: &str) -> String {
    format!(
        "{{ let value = {call}; let mut bytes = Vec::new(); {{ let out = &mut bytes; let part = &value; {} }} bytes }}",
        rust_write(data, "part")
    )
}

/// The adapter's serialization code for the library's data: a pair of
/// functions per record and per enum. An enum is matched by variant name in
/// both directions, so nothing here depends on its memory layout.
pub fn rust_codec(library: &Library) -> String {
    let mut out = String::new();
    for record in &library.records {
        let name = &record.name;
        let read: String = record
            .fields
            .iter()
            .map(|field| format!("\n        {}: {},", field.name, rust_read(&field.ty)))
            .collect();
        let mut written: String = record
            .fields
            .iter()
            .map(|field| {
                format!(
                    "\n    {{\n        let part = &value.{};\n        {}\n    }}",
                    field.name,
                    rust_write(&field.ty, "part")
                )
            })
            .collect();
        // Every record consumes at least one byte, including an empty one,
        // so collection counts can be bounded by the bytes remaining.
        let padding = if record.fields.is_empty() {
            written.push_str("\n    hxn_abi::wire::bool(out, false);");
            "\n    if input.bool()? { return Err(Fault::Encoding); }"
        } else {
            ""
        };
        out.push_str(&format!(
            "\n#[allow(dead_code)]\nfn {reader}(input: &mut hxn_abi::wire::Reader) -> Result<{name}, Fault> {{\n    input.enter()?;{padding}\n    let value = {name} {{{read}\n    }};\n    input.leave();\n    Ok(value)\n}}\n\n#[allow(dead_code, unused_variables)]\nfn {writer}(value: &{name}, out: &mut Vec<u8>) -> Result<(), Fault> {{{written}\n    Ok(())\n}}\n",
            reader = reader(name),
            writer = writer(name),
        ));
    }
    for tagged in &library.tagged {
        out.push_str(&tagged_codec(tagged));
    }
    for known in &library.enums {
        let name = &known.name;
        let read: String = known
            .variants
            .iter()
            .map(|variant| {
                format!(
                    "\n        value if value == {name}::{v} as i32 => Ok({name}::{v}),",
                    v = variant.name
                )
            })
            .collect();
        let written: String = known
            .variants
            .iter()
            .map(|variant| {
                format!(
                    "\n        {name}::{v} => {name}::{v} as i32,",
                    v = variant.name
                )
            })
            .collect();
        out.push_str(&format!(
            "\n#[allow(dead_code)]\nfn {reader}(value: i32) -> Result<{name}, Fault> {{\n    match value {{{read}\n        _ => Err(Fault::Range),\n    }}\n}}\n\n#[allow(dead_code)]\nfn {writer}(value: &{name}) -> i32 {{\n    match value {{{written}\n    }}\n}}\n",
            reader = reader(name),
            writer = writer(name),
        ));
    }
    out
}

// A variant as a pattern or an expression, with each field produced by `part`.
fn case_shape(tagged: &Tagged, case: &Case, part: impl Fn(usize) -> String) -> String {
    let path = format!("{}::{}", tagged.name, case.name);
    if case.fields.is_empty() {
        return path;
    }
    let parts: Vec<String> = case
        .fields
        .iter()
        .enumerate()
        .map(|(index, field)| {
            if case.named {
                format!("{}: {}", field.name, part(index))
            } else {
                part(index)
            }
        })
        .collect();
    if case.named {
        format!("{path} {{ {} }}", parts.join(", "))
    } else {
        format!("{path}({})", parts.join(", "))
    }
}

// The pair of functions for a tagged enum: the variant's index, then its
// fields. Fields are bound as `f0`, `f1` regardless of their names, so that
// none collides with a name the function uses.
fn tagged_codec(tagged: &Tagged) -> String {
    let name = &tagged.name;
    let read: String = tagged
        .cases
        .iter()
        .enumerate()
        .map(|(index, case)| {
            format!(
                "\n        {index} => {},",
                case_shape(tagged, case, |field| rust_read(&case.fields[field].ty))
            )
        })
        .collect();
    let written: String = tagged
        .cases
        .iter()
        .enumerate()
        .map(|(index, case)| {
            let fields: String = case
                .fields
                .iter()
                .enumerate()
                .map(|(field, held)| {
                    format!("\n            {}", rust_write(&held.ty, &format!("f{field}")))
                })
                .collect();
            format!(
                "\n        {} => {{\n            hxn_abi::wire::i32(out, {index});{fields}\n        }}",
                case_shape(tagged, case, |field| format!("f{field}"))
            )
        })
        .collect();
    format!(
        "\n#[allow(dead_code)]\nfn {reader}(input: &mut hxn_abi::wire::Reader) -> Result<{name}, Fault> {{\n    input.enter()?;\n    let value = match input.i32()? {{{read}\n        _ => return Err(Fault::Range),\n    }};\n    input.leave();\n    Ok(value)\n}}\n\n#[allow(dead_code, unused_variables)]\nfn {writer}(value: &{name}, out: &mut Vec<u8>) -> Result<(), Fault> {{\n    match value {{{written}\n    }}\n    Ok(())\n}}\n",
        reader = reader(name),
        writer = writer(name),
    )
}

/// The function that converts the error type `data` into a failure:
/// `hxn_thrown_pantry_error`.
pub fn thrower(data: &Data) -> String {
    format!("hxn_thrown_{}", snake(&data.name()))
}

/// Those functions, one per error type: the failure's message is the error's
/// own, and its value is the error type's index followed by the serialized
/// error.
pub fn rust_throwers(library: &Library) -> String {
    let mut out = String::new();
    for (place, error) in library.errors().into_iter().enumerate() {
        let name = error.name();
        let write = match error {
            Data::Enum(known) => format!(
                "hxn_abi::wire::i32(&mut value, {}(&error));\n    failure.with_value(value)",
                writer(known)
            ),
            // An error that fails to serialize still produces a failure with
            // a message.
            _ => format!(
                "match {}(&error, &mut value) {{\n        Ok(()) => failure.with_value(value),\n        Err(_) => failure,\n    }}",
                writer(&name)
            ),
        };
        out.push_str(&format!(
            "\n#[allow(dead_code)]\nfn {thrower}(error: {name}) -> hxn_abi::Failure {{\n    let failure = hxn_abi::Failure::new(Status::ERROR, error.to_string());\n    let mut value = Vec::new();\n    hxn_abi::wire::i32(&mut value, {place});\n    {write}\n}}\n",
            thrower = thrower(error),
        ));
    }
    out
}

/// The Haxe type of `data`.
pub fn haxe_type(data: &Data) -> String {
    match data {
        Data::Bool => String::from("Bool"),
        Data::I32 => String::from("Int"),
        Data::I64 | Data::Number(Number::U64) => String::from("haxe.Int64"),
        Data::F64 | Data::Number(Number::F32) => String::from("Float"),
        Data::Number(Number::U32) => String::from("UInt"),
        Data::Number(_) => String::from("Int"),
        Data::Text => String::from("String"),
        Data::Bytes => String::from("haxe.io.Bytes"),
        Data::Enum(name) | Data::Record(name) | Data::Tagged(name) => name.clone(),
        Data::Option(of) => format!("Null<{}>", haxe_type(of)),
        Data::List(of) => format!("Array<{}>", haxe_type(of)),
        Data::Tuple(parts) => format!(
            "{{ {} }}",
            parts
                .iter()
                .enumerate()
                .map(|(index, part)| format!("_{index}: {}", haxe_type(part)))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Data::Set { of, .. } => format!("hxn.Set<{}>", haxe_type(of)),
        Data::Boxed(of) => haxe_type(of),
        Data::Map { key, value, .. } => format!("Map<{}, {}>", haxe_type(key), haxe_type(value)),
    }
}

/// The Haxe statements that serialize `value` into the buffer `out`. `depth`
/// keeps the loop variables of nested lists distinct. A null where a value is
/// required throws here, not in native code.
pub fn haxe_write(data: &Data, value: &str, out: &str, depth: usize) -> Vec<String> {
    match data {
        Data::Bool => vec![format!("{out}.addByte({value} ? 1 : 0);")],
        Data::I32 | Data::Enum(_) => vec![format!("{out}.addInt32({value});")],
        Data::Number(Number::U64) | Data::I64 => vec![format!("{out}.addInt64({value});")],
        Data::F64 | Data::Number(Number::F32) => vec![format!("{out}.addDouble({value});")],
        Data::Number(_) => vec![format!("{out}.addInt32({value});")],
        Data::Text => vec![format!("hxn.Wire.text({out}, {value});")],
        Data::Bytes => vec![format!("hxn.Wire.bytes({out}, {value});")],
        Data::Record(name) => vec![
            format!("if ({value} == null)"),
            format!("\tthrow new haxe.Exception(\"null where a {name} is needed\");"),
            format!("{value}.hxnWrite({out});"),
        ],
        Data::Tagged(name) => vec![
            format!("if ({value} == null)"),
            format!("\tthrow new haxe.Exception(\"null where a {name} is needed\");"),
            format!("{}.write({value}, {out});", wire_class(name)),
        ],
        Data::Boxed(of) => haxe_write(of, value, out, depth),
        Data::Tuple(parts) => {
            let mut lines = vec![
                format!("if ({value} == null)"),
                String::from("\tthrow new haxe.Exception(\"null where a tuple is needed\");"),
            ];
            for (index, part) in parts.iter().enumerate() {
                lines.extend(haxe_write(part, &format!("{value}._{index}"), out, depth));
            }
            lines
        }
        Data::Map {
            key, value: held, ..
        } => {
            let (each, item) = (format!("key{depth}"), format!("item{depth}"));
            let mut lines = vec![
                format!("if ({value} == null)"),
                String::from("\tthrow new haxe.Exception(\"null where a map is needed\");"),
                format!("{out}.addInt32(Lambda.count({value}));"),
                format!("for ({each} => {item} in {value}) {{"),
            ];
            for line in haxe_write(key, &each, out, depth + 1)
                .into_iter()
                .chain(haxe_write(held, &item, out, depth + 1))
            {
                lines.push(format!("\t{line}"));
            }
            lines.push(String::from("}"));
            lines
        }
        Data::Option(of) => {
            let mut lines = vec![format!("if ({value} == null)")];
            lines.push(format!("\t{out}.addByte(0);"));
            lines.push(String::from("else {"));
            lines.push(format!("\t{out}.addByte(1);"));
            for line in haxe_write(of, value, out, depth) {
                lines.push(format!("\t{line}"));
            }
            lines.push(String::from("}"));
            lines
        }
        Data::List(of) | Data::Set { of, .. } => {
            let item = format!("item{depth}");
            let kind = if matches!(data, Data::Set { .. }) {
                "set"
            } else {
                "list"
            };
            let mut lines = vec![
                format!("if ({value} == null)"),
                format!("\tthrow new haxe.Exception(\"null where a {kind} is needed\");"),
                format!("{out}.addInt32({value}.length);"),
                format!("for ({item} in {value}) {{"),
            ];
            for line in haxe_write(of, &item, out, depth + 1) {
                lines.push(format!("\t{line}"));
            }
            lines.push(String::from("}"));
            lines
        }
    }
}

/// The Haxe expression that deserializes `data` from `input`.
pub fn haxe_read(data: &Data) -> String {
    match data {
        Data::Bool => String::from("input.readByte() != 0"),
        Data::I32 | Data::Number(Number::I8 | Number::I16 | Number::U8 | Number::U16) => {
            String::from("input.readInt32()")
        }
        Data::Number(Number::Isize | Number::Usize) => String::from("input.readInt32()"),
        Data::Number(Number::U32) => String::from("(input.readInt32() : UInt)"),
        Data::I64 | Data::Number(Number::U64) => String::from("hxn.Wire.readInt64(input)"),
        Data::F64 | Data::Number(Number::F32) => String::from("input.readDouble()"),
        Data::Text => String::from("hxn.Wire.readText(input)"),
        Data::Bytes => String::from("hxn.Wire.readBytes(input)"),
        Data::Enum(name) => format!("(input.readInt32() : {name})"),
        Data::Record(name) => format!("{name}.hxnRead(input)"),
        Data::Tagged(name) => format!("{}.read(input)", wire_class(name)),
        Data::Boxed(of) => haxe_read(of),
        Data::Tuple(parts) => {
            // Read in order, before constructing the anonymous record.
            let read = parts
                .iter()
                .enumerate()
                .map(|(index, part)| format!("var p{index} = {}; ", haxe_read(part)))
                .collect::<String>();
            let fields = (0..parts.len())
                .map(|index| format!("_{index}: p{index}"))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ {read}{{ {fields} }}; }}")
        }
        // Each read is a separate statement, so the key is read first.
        Data::Map { key, value, .. } => format!(
            "{{ var made = new {}(); for (_ in 0...input.readInt32()) {{ var key = {}; var value = {}; made.set(key, value); }} made; }}",
            haxe_type(data),
            haxe_read(key),
            haxe_read(value)
        ),
        Data::Option(of) => format!(
            "(input.readByte() == 0 ? null : {} : {})",
            haxe_read(of),
            haxe_type(data)
        ),
        Data::List(of) => format!("[for (_ in 0...input.readInt32()) {}]", haxe_read(of)),
        Data::Set { of, .. } => format!(
            "new hxn.Set<{}>([for (_ in 0...input.readInt32()) {}])",
            haxe_type(of),
            haxe_read(of)
        ),
    }
}

fn record_file(record: &Record) -> File {
    let name = &record.name;
    let mut out = String::from(HEADER);
    out.push_str(&docs(&record.docs, ""));
    // Constructed from its fields by name, as `{label: "x", enabled: true}`.
    out.push_str(&format!("@:structInit class {name} {{\n"));
    for field in &record.fields {
        out.push_str(&docs(&field.docs, "\t"));
        // An optional field can be omitted.
        let unset = if matches!(field.ty, Data::Option(_)) {
            " = null"
        } else {
            ""
        };
        out.push_str(&format!(
            "\tpublic var {}:{}{unset};\n",
            camel(&field.name),
            haxe_type(&field.ty)
        ));
    }
    out.push_str("\n\t/** Writes the fields in order, as the library reads them. **/\n\t@:noCompletion public function hxnWrite(out:haxe.io.BytesBuffer):Void {\n");
    if record.fields.is_empty() {
        out.push_str("\t\tout.addByte(0);\n");
    }
    for field in &record.fields {
        for line in haxe_write(&field.ty, &camel(&field.name), "out", 0) {
            out.push_str(&format!("\t\t{line}\n"));
        }
    }
    out.push_str("\t}\n\n\t/** Reads what the library wrote. **/\n");
    out.push_str(&format!(
        "\t@:noCompletion public static function hxnRead(input:haxe.io.BytesInput):{name} {{\n"
    ));
    if record.fields.is_empty() {
        out.push_str("\t\tif (input.readByte() != 0)\n\t\t\tthrow new haxe.Exception(\"invalid empty record\");\n");
    }
    for field in &record.fields {
        out.push_str(&format!(
            "\t\tvar {}:{} = {};\n",
            camel(&field.name),
            haxe_type(&field.ty),
            haxe_read(&field.ty)
        ));
    }
    let fields: Vec<String> = record
        .fields
        .iter()
        .map(|field| {
            let name = camel(&field.name);
            format!("{name}: {name}")
        })
        .collect();
    out.push_str(&format!(
        "\t\tvar made:{name} = {{{}}};\n\t\treturn made;\n\t}}\n}}\n",
        fields.join(", ")
    ));
    File {
        path: format!("{name}.hx"),
        text: out,
    }
}

fn enum_file(known: &Enumeration) -> File {
    let name = &known.name;
    let mut out = String::from(HEADER);
    out.push_str(&docs(&known.docs, ""));
    out.push_str(&format!("enum abstract {name}(Int) from Int to Int {{\n"));
    for variant in &known.variants {
        out.push_str(&docs(&variant.docs, "\t"));
        out.push_str(&format!("\tvar {} = {};\n", variant.name, variant.value));
    }
    out.push_str("}\n");
    File {
        path: format!("{name}.hx"),
        text: out,
    }
}

// The Haxe names of a variant's fields: `value`, `done`.
fn case_fields(case: &Case) -> Vec<String> {
    case.fields.iter().map(|field| camel(&field.name)).collect()
}

fn tagged_file(tagged: &Tagged) -> File {
    let name = &tagged.name;
    let mut out = String::from(HEADER);
    out.push_str(&docs(&tagged.docs, ""));
    out.push_str(&format!("enum {name} {{\n"));
    for case in &tagged.cases {
        out.push_str(&docs(&case.docs, "\t"));
        let fields: Vec<String> = case
            .fields
            .iter()
            .map(|field| format!("{}:{}", camel(&field.name), haxe_type(&field.ty)))
            .collect();
        if fields.is_empty() {
            out.push_str(&format!("\t{};\n", case.name));
        } else {
            out.push_str(&format!("\t{}({});\n", case.name, fields.join(", ")));
        }
    }
    out.push_str("}\n");
    File {
        path: format!("{name}.hx"),
        text: out,
    }
}

// A Haxe enum cannot have methods, so a separate class serializes and
// deserializes it: the variant's index, then its fields.
fn tagged_wire_file(tagged: &Tagged) -> File {
    let name = &tagged.name;
    let class = wire_class(name);
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "/** Writes a `{name}` as the library reads it, and reads what the library wrote. **/\n@:noCompletion class {class} {{\n\tpublic static function write(value:{name}, out:haxe.io.BytesBuffer):Void {{\n\t\tswitch (value) {{\n"
    ));
    for (index, case) in tagged.cases.iter().enumerate() {
        let fields = case_fields(case);
        if fields.is_empty() {
            out.push_str(&format!("\t\t\tcase {}:\n", case.name));
        } else {
            out.push_str(&format!(
                "\t\t\tcase {}({}):\n",
                case.name,
                fields.join(", ")
            ));
        }
        out.push_str(&format!("\t\t\t\tout.addInt32({index});\n"));
        for (field, held) in fields.iter().zip(&case.fields) {
            for line in haxe_write(&held.ty, field, "out", 0) {
                out.push_str(&format!("\t\t\t\t{line}\n"));
            }
        }
    }
    out.push_str(&format!(
        "\t\t}}\n\t}}\n\n\tpublic static function read(input:haxe.io.BytesInput):{name} {{\n\t\tswitch (input.readInt32()) {{\n"
    ));
    for (index, case) in tagged.cases.iter().enumerate() {
        out.push_str(&format!("\t\t\tcase {index}:\n"));
        let fields = case_fields(case);
        // Each field is read by a separate statement, in order.
        for (field, held) in fields.iter().zip(&case.fields) {
            out.push_str(&format!(
                "\t\t\t\tvar {field}:{} = {};\n",
                haxe_type(&held.ty),
                haxe_read(&held.ty)
            ));
        }
        if fields.is_empty() {
            out.push_str(&format!("\t\t\t\treturn {name}.{};\n", case.name));
        } else {
            out.push_str(&format!(
                "\t\t\t\treturn {name}.{}({});\n",
                case.name,
                fields.join(", ")
            ));
        }
    }
    out.push_str(&format!(
        "\t\t\tcase _:\n\t\t\t\tthrow new haxe.Exception(\"not a case of {name}\");\n\t\t}}\n\t}}\n}}\n"
    ));
    File {
        path: format!("{class}.hx"),
        text: out,
    }
}

// The exception class thrown for a failure with the error type `error`.
fn exception_file(error: &Data) -> File {
    let name = error.name();
    let class = exception_class(&name);
    File {
        path: format!("{class}.hx"),
        text: format!(
            "{HEADER}/** Thrown where the library fails with a `{name}`, which is `error`. **/\nclass {class} extends haxe.Exception {{\n\tpublic final error:{name};\n\n\tpublic function new(message:String, error:{name}, ?previous:haxe.Exception) {{\n\t\tsuper(message, previous);\n\t\tthis.error = error;\n\t}}\n}}\n"
        ),
    }
}

/// The Haxe classes of the library's data: the same on every runtime.
pub fn haxe_files(library: &Library) -> Vec<File> {
    let mut files: Vec<File> = library.records.iter().map(record_file).collect();
    files.extend(library.enums.iter().map(enum_file));
    for tagged in &library.tagged {
        files.push(tagged_file(tagged));
        files.push(tagged_wire_file(tagged));
    }
    files.extend(library.errors().into_iter().map(exception_file));
    files
}
