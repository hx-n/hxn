//! The two Rust adapters: one over the plain C ABI, for hxcpp, and one of
//! HashLink primitives. Each is the text of a file a thin crate includes.

use crate::later;
use crate::lent;
use crate::model::{Interface, Library, Method, Param, Receiver, Type};
use crate::names::{
    abstract_name, cell_abstract, cell_export, export, has_receiver, held_export, local, release,
    wanted_export, weak_abstract,
};

const HEADER: &str = "// Generated by hxn-gen from the library's source. Do not edit.\n";

fn question(method: &Method) -> &'static str {
    if method.fallible { "?" } else { "" }
}

// `this.add(amount)` or `Counter::live()`.
fn call(interface: &Interface, method: &Method, arguments: &[String]) -> String {
    let target = if has_receiver(method) {
        format!("this.{}", method.name)
    } else {
        format!("{}::{}", interface.name, method.name)
    };
    format!("{target}({}){}", arguments.join(", "), question(method))
}

// The receiver as `this`, borrowed or taken from what `open` yields: a
// `Result` of the handle behind the pointer.
fn receiver(method: &Method, open: &str) -> Option<String> {
    match method.receiver {
        Receiver::None => None,
        Receiver::Shared => Some(format!("let this = {open}?.borrow()?;")),
        Receiver::Exclusive => Some(format!("let mut this = {open}?.borrow_mut()?;")),
        // Taken out, so the Haxe object is closed whatever the call does.
        Receiver::Owned => Some(format!("let this = {open}?.take()?.ok_or(Fault::Closed)?;")),
    }
}

// What a handle of `interface` holds: the value, or an `Arc` of it.
pub(crate) fn held(library: &Library, interface: &str) -> String {
    if library.is_shared(interface) {
        format!("Arc<{interface}>")
    } else {
        interface.to_owned()
    }
}

// A result of an interface as the pointer the host gets. `into` makes one
// from what a handle holds.
fn handed(library: &Library, method: &Method, call: &str, into: &str) -> String {
    let Type::Handle {
        interface,
        nullable,
    } = &method.returns
    else {
        unreachable!("not an interface");
    };
    let wrap = library.is_shared(interface) && !method.returns_arc;
    match (nullable, wrap) {
        (false, false) => format!("Ok({into}({call}))"),
        (false, true) => format!("Ok({into}(Arc::new({call})))"),
        (true, false) => format!("Ok({call}.map_or(null_mut(), {into}))"),
        (true, true) => format!("Ok({call}.map(Arc::new).map_or(null_mut(), {into}))"),
    }
}

// A borrowed interface: the statement that borrows it, and the argument.
// `open` turns the parameter's name into a `Result` of its handle. A shared
// one is borrowed as its `Arc`, which gives the value or a share of it.
fn borrowed(
    param: &Param,
    nullable: bool,
    shared: bool,
    open: impl Fn(&str) -> String,
) -> (String, String) {
    let name = &param.name;
    let (borrow, mutable) = if param.exclusive {
        ("borrow_mut", "mut ")
    } else {
        ("borrow", "")
    };
    let opened = open(name);
    if nullable {
        let argument = if param.kept {
            format!("{name}.as_deref().cloned()")
        } else if shared {
            format!("{name}.as_deref().map(Arc::as_ref)")
        } else if param.exclusive {
            format!("{name}.as_deref_mut()")
        } else {
            format!("{name}.as_deref()")
        };
        (
            format!(
                "let {mutable}{name} = if {name}.is_null() {{ None }} else {{ Some({opened}?.{borrow}()?) }};"
            ),
            argument,
        )
    } else {
        let argument = if param.kept {
            format!("Arc::clone(&{name})")
        } else if param.exclusive {
            format!("&mut {name}")
        } else {
            format!("&{name}")
        };
        (
            format!("let {mutable}{name} = {opened}?.{borrow}()?;"),
            argument,
        )
    }
}

// A cell the host lent: the statement that turns its address into a
// reference, refusing a null one, and the argument.
fn lent(param: &Param) -> (String, String) {
    let name = &param.name;
    let ty = if param.ty == Type::AtomicBool {
        "AtomicFlag"
    } else {
        "AtomicI32"
    };
    (
        format!(
            "let {name} = if {name}.is_null() {{ return Err(Fault::Null.into()); }} else {{ {ty}::from_ptr({name}) }};"
        ),
        name.clone(),
    )
}

// A function generic in its callback's error fails here with the adapter's
// own, which makes the `?` on its result a conversion to the same type.
fn lent_allow(method: &Method) -> &'static str {
    if method.params.iter().any(|p| lent::of(&p.ty).is_some()) {
        "#[allow(clippy::needless_question_mark)]\n"
    } else {
        ""
    }
}

fn c_method(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut params = Vec::new();
    let mut body = Vec::new();
    if let Some(this) = receiver(
        method,
        &format!(
            "Handle::<{}>::from_raw(this)",
            held(library, &interface.name)
        ),
    ) {
        params.push(String::from("this: RawHandle"));
        body.push(this);
    }
    let mut arguments = Vec::new();
    for param in &method.params {
        let name = &param.name;
        if let Some((taken, given)) = lent::of(&param.ty) {
            params.push(format!("{name}: Callback<{}>", lent::alias(taken, given)));
            arguments.push(lent::closure(name, taken, given));
            continue;
        }
        let (ty, argument) = match &param.ty {
            // An int at the boundary: C has no one size for a bool.
            Type::Bool => ("i32", format!("{name} != 0")),
            Type::I32 => ("i32", name.clone()),
            Type::F64 => ("f64", name.clone()),
            Type::Str => ("Slice<'_>", format!("{name}.as_str()?")),
            Type::Bytes => ("Slice<'_>", format!("{name}.as_bytes()?")),
            Type::Handle {
                interface,
                nullable,
            } => {
                let of = held(library, interface);
                let (statement, argument) =
                    borrowed(param, *nullable, library.is_shared(interface), |name| {
                        format!("Handle::<{of}>::from_raw({name})")
                    });
                body.push(statement);
                ("RawHandle", argument)
            }
            Type::AtomicInt | Type::AtomicBool => {
                let (statement, argument) = lent(param);
                body.push(statement);
                ("*mut i32", argument)
            }
            Type::Void
            | Type::Future(_)
            | Type::Stream(_)
            | Type::Signal(_)
            | Type::Lent { .. } => {
                unreachable!("not a parameter type")
            }
        };
        params.push(format!("{name}: {ty}"));
        arguments.push(argument);
    }
    let call = call(interface, method, &arguments);
    let (out, result) = match &method.returns {
        Type::Void => (None, format!("{call};\n            Ok(())")),
        Type::Bool => (Some("i32"), format!("Ok(i32::from({call}))")),
        Type::I32 => (Some("i32"), format!("Ok({call})")),
        Type::F64 => (Some("f64"), format!("Ok({call})")),
        Type::Str | Type::Bytes => (Some("Buf"), format!("Ok(Buf::from({call}))")),
        Type::Lent { .. } => unreachable!("not a result type"),
        Type::Handle { .. } => (
            Some("RawHandle"),
            handed(library, method, &call, "Handle::into_raw"),
        ),
        // Handed over as the integer cell both kinds are, with the handle
        // keeping it alive.
        Type::Future(_) | Type::Stream(_) | Type::Signal(_) => {
            let (kind, _) = later::of(&method.returns).expect("a result over time");
            (Some("RawHandle"), later::c_result(kind, &call))
        }
        Type::AtomicInt => (Some("RawHandle"), format!("Ok(Handle::into_raw({call}))")),
        Type::AtomicBool => (
            Some("RawHandle"),
            format!("Ok(Handle::into_raw(AtomicFlag::into_int({call})))"),
        ),
    };
    let out_argument = match out {
        Some(ty) => {
            params.push(format!("out: *mut {ty}"));
            "out"
        }
        None => "null_mut::<()>()",
    };
    params.push(String::from("err: *mut Buf"));
    body.push(result);
    format!(
        "{allow}#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({params}) -> Status {{\n    unsafe {{\n        guard({out_argument}, err, || {{\n            {body}\n        }})\n    }}\n}}\n",
        allow = lent_allow(method),
        name = export(library, &interface.name, &method.name),
        params = params.join(", "),
        body = body.join("\n            "),
    )
}

// What every shared interface has: whether two handles hold one value, a
// weak reference to it, and that reference's own upgrade and close.
fn c_shared(library: &Library, interface: &Interface) -> String {
    let name = &interface.name;
    format!(
        "\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {same}(this: RawHandle, other: RawHandle, out: *mut i32, err: *mut Buf) -> Status {{\n    unsafe {{\n        guard(out, err, || {{\n            let this = Handle::<Arc<{name}>>::from_raw(this)?.borrow()?;\n            if other.is_null() {{\n                return Ok(0);\n            }}\n            let other = Handle::<Arc<{name}>>::from_raw(other)?.borrow()?;\n            Ok(i32::from(Arc::ptr_eq(&this, &other)))\n        }})\n    }}\n}}\n\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {weak}(this: RawHandle, out: *mut RawHandle, err: *mut Buf) -> Status {{\n    unsafe {{\n        guard(out, err, || {{\n            let this = Handle::<Arc<{name}>>::from_raw(this)?.borrow()?;\n            Ok(Handle::into_raw(Arc::downgrade(&this)))\n        }})\n    }}\n}}\n\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {upgrade}(this: RawHandle, out: *mut RawHandle, err: *mut Buf) -> Status {{\n    unsafe {{\n        guard(out, err, || {{\n            let this = Handle::<Weak<{name}>>::from_raw(this)?.borrow()?;\n            Ok(this.upgrade().map_or(null_mut(), Handle::into_raw))\n        }})\n    }}\n}}\n\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {close}(this: RawHandle, err: *mut Buf) -> Status {{\n    unsafe {{\n        guard(null_mut::<()>(), err, || {{\n            Handle::<Weak<{name}>>::from_raw(this)?.take()?;\n            Ok(())\n        }})\n    }}\n}}\n",
        same = export(library, name, "same"),
        weak = export(library, name, "weak"),
        upgrade = export(library, name, "weak_upgrade"),
        close = export(library, name, "weak_close"),
    )
}

fn hl_shared(library: &Library, interface: &Interface) -> String {
    let name = &interface.name;
    let own = abstract_name(library, name);
    let weak_abstract = weak_abstract(library, name);
    let mut out = String::new();
    let mut prim = |method: &str, signature: String, params: &str, returns: &str, body: &str| {
        let export = export(library, name, method);
        out.push_str(&format!(
            "\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {export}({params}){returns} {{\n    unsafe {{\n        prim(|| {{\n            {body}\n        }})\n    }}\n}}\ndefine_prim!(hlp_{local}, {export}, \"{signature}\");\n",
            local = local(name, method),
        ));
    };
    prim(
        "same",
        format!("PX{own}_X{own}__b"),
        "this: *mut Managed, other: *mut Managed",
        " -> bool",
        &format!(
            "let this = handle::<Arc<{name}>>(this)?.borrow()?;\n            if other.is_null() {{\n                return Ok(false);\n            }}\n            let other = handle::<Arc<{name}>>(other)?.borrow()?;\n            Ok(Arc::ptr_eq(&this, &other))"
        ),
    );
    prim(
        "weak",
        format!("PX{own}__X{weak_abstract}_"),
        "this: *mut Managed",
        " -> *mut Managed",
        &format!(
            "let this = handle::<Arc<{name}>>(this)?.borrow()?;\n            Ok(manage(Arc::downgrade(&this)))"
        ),
    );
    prim(
        "weak_upgrade",
        format!("PX{weak_abstract}__X{own}_"),
        "this: *mut Managed",
        " -> *mut Managed",
        &format!(
            "let this = handle::<Weak<{name}>>(this)?.borrow()?;\n            Ok(this.upgrade().map_or(null_mut(), manage))"
        ),
    );
    prim(
        "weak_close",
        format!("PX{weak_abstract}__v"),
        "this: *mut Managed",
        "",
        &format!("handle::<Weak<{name}>>(this)?.take()?;\n            Ok(())"),
    );
    out
}

fn imports(library: &Library, core: &str) -> String {
    let names: Vec<&str> = library
        .interfaces
        .iter()
        .map(|interface| interface.name.as_str())
        .collect();
    match names.as_slice() {
        [] => String::new(),
        [name] => format!("use {core}::{name};\n"),
        names => format!("use {core}::{{{}}};\n", names.join(", ")),
    }
}

/// The adapter over the plain C ABI. `core` is the path the library's items
/// are found under, such as `counter_core`.
pub fn c_adapter(library: &Library, core: &str) -> String {
    let mut out = String::from(HEADER);
    out.push_str("\n#[allow(unused_imports)]\nuse std::ffi::c_void;\n");
    out.push_str("#[allow(unused_imports)]\nuse std::ptr::null_mut;\n");
    out.push_str("#[allow(unused_imports)]\nuse std::sync::{Arc, Weak};\n");
    out.push_str("#[allow(unused_imports)]\nuse std::sync::atomic::AtomicI32;\n\n");
    out.push_str(
        "#[allow(unused_imports)]\nuse hxn_abi::{AtomicFlag, Buf, Callback, Fault, Handle, RawHandle, Slice, Status, guard, memory, release};\n",
    );
    out.push_str(&imports(library, core));
    out.push_str(later::imports(library));
    out.push_str(&lent::aliases(library));
    for interface in &library.interfaces {
        for method in &interface.methods {
            out.push('\n');
            out.push_str(&c_method(library, interface, method));
        }
        out.push_str(&format!(
            "\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}(this: RawHandle, err: *mut Buf) -> Status {{\n    unsafe {{\n        guard(null_mut::<()>(), err, || {{\n            Handle::<{held}>::from_raw(this)?.take()?;\n            Ok(())\n        }})\n    }}\n}}\n",
            name = export(library, &interface.name, "close"),
            held = held(library, &interface.name),
        ));
        if interface.shared {
            out.push_str(&c_shared(library, interface));
        }
    }
    if library.returns_cells() {
        out.push_str(&format!(
            "\n// Where a cell the library handed over is, for the host's own atomic operations.\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}(this: RawHandle, out: *mut *mut i32, err: *mut Buf) -> Status {{\n    unsafe {{\n        guard(out, err, || {{\n            Ok(Handle::<Arc<AtomicI32>>::from_raw(this)?.borrow()?.as_ptr())\n        }})\n    }}\n}}\n",
            cell_export(library)
        ));
    }
    out.push_str(&later::c_adapter(library));
    out.push_str(&format!(
        "\n// What the library's values hold that the host's collector cannot see, and\n// whether the library asked for a collection since the last call.\n#[unsafe(no_mangle)]\npub extern \"C\" fn {held}() -> f64 {{\n    memory::held() as f64\n}}\n\n#[unsafe(no_mangle)]\npub extern \"C\" fn {wanted}() -> i32 {{\n    i32::from(memory::take_request())\n}}\n",
        held = held_export(library),
        wanted = wanted_export(library),
    ));
    out.push_str(&format!(
        "\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}(this: RawHandle) {{\n    unsafe {{ release(this) }}\n}}\n",
        release(library)
    ));
    out
}

fn hl_letter(library: &Library, ty: &Type) -> String {
    match ty {
        Type::Void => String::from("v"),
        Type::Bool => String::from("b"),
        Type::I32 => String::from("i"),
        Type::F64 => String::from("d"),
        // A result: UTF-16 bytes for `String.fromUCS2`.
        // Bytes are the VM's own, with their length written beside them.
        Type::Str | Type::Bytes => String::from("B"),
        Type::Lent { .. } => unreachable!("not a result type"),
        Type::Handle { interface, .. } => format!("X{}_", abstract_name(library, interface)),
        Type::AtomicInt | Type::AtomicBool => format!("X{}_", cell_abstract(library)),
        Type::Future(_) | Type::Stream(_) | Type::Signal(_) => {
            let (kind, _) = later::of(ty).expect("a result over time");
            format!("X{}_", later::handle_abstract(library, kind))
        }
    }
}

fn hl_method(library: &Library, interface: &Interface, method: &Method) -> String {
    let own = abstract_name(library, &interface.name);
    let mut params = Vec::new();
    let mut signature = String::new();
    let mut body = Vec::new();
    if let Some(this) = receiver(
        method,
        &format!("handle::<{}>(this)", held(library, &interface.name)),
    ) {
        params.push(String::from("this: *mut Managed"));
        signature.push_str(&format!("X{own}_"));
        body.push(this);
    }
    let mut arguments = Vec::new();
    for param in &method.params {
        let name = &param.name;
        if let Some((taken, given)) = lent::of(&param.ty) {
            params.push(format!("{name}: *mut vclosure"));
            signature.push_str(&lent::hl_signature(taken, given));
            // Lent: the VM keeps it alive for the call, so nothing is dropped.
            body.push(format!(
                "if {name}.is_null() {{\n                return Err(Fault::Null.into());\n            }}"
            ));
            body.push(format!(
                "let {name} = Callback::from_raw({} as {}, {name}.cast(), None);",
                lent::trampoline(taken, given),
                lent::alias(taken, given)
            ));
            arguments.push(lent::closure(name, taken, given));
            continue;
        }
        match &param.ty {
            Type::Bool => {
                params.push(format!("{name}: bool"));
                signature.push('b');
                arguments.push(name.clone());
            }
            Type::I32 => {
                params.push(format!("{name}: i32"));
                signature.push('i');
                arguments.push(name.clone());
            }
            Type::F64 => {
                params.push(format!("{name}: f64"));
                signature.push('d');
                arguments.push(name.clone());
            }
            Type::Str => {
                params.push(format!("{name}: *mut vstring"));
                signature.push_str("OBi_");
                body.push(format!("let {name} = string({name})?.unwrap_or_default();"));
                arguments.push(format!("&{name}"));
            }
            Type::Bytes => {
                params.push(format!("{name}: *mut vbyte"));
                params.push(format!("{name}_length: i32"));
                signature.push_str("Bi");
                body.push(format!(
                    "let {name} = slice({name}, {name}_length).as_bytes()?;"
                ));
                arguments.push(name.clone());
            }
            Type::Handle {
                interface,
                nullable,
            } => {
                params.push(format!("{name}: *mut Managed"));
                signature.push_str(&hl_letter(library, &param.ty));
                let of = held(library, interface);
                let (statement, argument) =
                    borrowed(param, *nullable, library.is_shared(interface), |name| {
                        format!("handle::<{of}>({name})")
                    });
                body.push(statement);
                arguments.push(argument);
            }
            Type::AtomicInt | Type::AtomicBool => {
                params.push(format!("{name}: *mut i32"));
                // A reference to an int, which is what the VM's own atomic
                // operations take.
                signature.push_str("Ri");
                let (statement, argument) = lent(param);
                body.push(statement);
                arguments.push(argument);
            }
            Type::Void
            | Type::Future(_)
            | Type::Stream(_)
            | Type::Signal(_)
            | Type::Lent { .. } => {
                unreachable!("not a parameter type")
            }
        }
    }
    if method.returns == Type::Bytes {
        // The VM's bytes do not say how long they are.
        params.push(String::from("out: *mut i32"));
        signature.push_str("Ri");
    }
    let mut call = call(interface, method, &arguments);
    if method.blocking {
        // Everything the call reads was copied or borrowed above.
        let inner = call.trim_end_matches('?').to_owned();
        call = format!("blocking(|| {inner}){}", question(method));
    }
    let (ty, result) = match &method.returns {
        Type::Void => ("()", format!("{call};\n            Ok(())")),
        Type::Bool => ("bool", format!("Ok({call})")),
        Type::I32 => ("i32", format!("Ok({call})")),
        Type::F64 => ("f64", format!("Ok({call})")),
        Type::Str => ("*mut vbyte", format!("Ok(utf16(&{call}))")),
        Type::Lent { .. } => unreachable!("not a result type"),
        Type::Handle { .. } => ("*mut Managed", handed(library, method, &call, "manage")),
        Type::Future(_) | Type::Stream(_) | Type::Signal(_) => {
            let (kind, _) = later::of(&method.returns).expect("a result over time");
            ("*mut Managed", later::hl_result(kind, &call))
        }
        Type::AtomicInt => ("*mut Managed", format!("Ok(manage({call}))")),
        Type::AtomicBool => (
            "*mut Managed",
            format!("Ok(manage(AtomicFlag::into_int({call})))"),
        ),
        Type::Bytes => (
            "*mut vbyte",
            format!(
                "let data = {call};\n            if out.is_null() {{\n                return Err(Fault::Null.into());\n            }}\n            *out = i32::try_from(data.len()).map_err(|_| Fault::TooLarge)?;\n            Ok(bytes(&data))"
            ),
        ),
    };
    body.push(result);
    let name = export(library, &interface.name, &method.name);
    let returns = if ty == "()" {
        String::new()
    } else {
        format!(" -> {ty}")
    };
    format!(
        "{allow}#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({params}){returns} {{\n    unsafe {{\n        prim(|| {{\n            {body}\n        }})\n    }}\n}}\ndefine_prim!(hlp_{local}, {name}, \"P{signature}_{ret}\");\n",
        allow = lent_allow(method),
        params = params.join(", "),
        body = body.join("\n            "),
        local = local(&interface.name, &method.name),
        ret = hl_letter(library, &method.returns),
    )
}

/// The adapter of HashLink primitives, for an `.hdll` or a wasm side module.
pub fn hl_adapter(library: &Library, core: &str) -> String {
    let mut out = String::from(HEADER);
    out.push_str("\n#[allow(unused_imports)]\nuse std::ffi::c_void;\n");
    out.push_str("#[allow(unused_imports)]\nuse std::ptr::null_mut;\n\n");
    out.push_str("#[allow(unused_imports)]\nuse std::sync::{Arc, Weak};\n");
    out.push_str("#[allow(unused_imports)]\nuse std::sync::atomic::AtomicI32;\n\n");
    out.push_str(
        "#[allow(unused_imports)]\nuse hxn_abi::{AtomicFlag, Callback, Fault, Status, memory};\n",
    );
    out.push_str(
        "#[allow(unused_imports)]\nuse hxn_hl::{Managed, blocking, box_bool, box_f64, box_i32, bytes, call, define_prim, handle, manage, prim, slice, string, unbox_bool, unbox_f64, unbox_i32, utf16, vbyte, vclosure, vdynamic, vstring};\n",
    );
    out.push_str(&imports(library, core));
    out.push_str(later::imports(library));
    out.push_str(&lent::aliases(library));
    out.push_str(&lent::hl_trampolines(library));
    for interface in &library.interfaces {
        let own = abstract_name(library, &interface.name);
        for method in &interface.methods {
            out.push('\n');
            out.push_str(&hl_method(library, interface, method));
        }
        let name = export(library, &interface.name, "close");
        out.push_str(&format!(
            "\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}(this: *mut Managed) {{\n    unsafe {{\n        prim(|| {{\n            handle::<{held}>(this)?.take()?;\n            Ok(())\n        }})\n    }}\n}}\ndefine_prim!(hlp_{local}, {name}, \"PX{own}__v\");\n",
            held = held(library, &interface.name),
            local = local(&interface.name, "close"),
        ));
        if interface.shared {
            out.push_str(&hl_shared(library, interface));
        }
    }
    if library.returns_cells() {
        let name = cell_export(library);
        out.push_str(&format!(
            "\n// Where a cell the library handed over is, for the VM's own atomic operations.\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}(this: *mut Managed) -> *mut i32 {{\n    unsafe {{ prim(|| Ok(handle::<Arc<AtomicI32>>(this)?.borrow()?.as_ptr())) }}\n}}\ndefine_prim!(hlp_atomic_cell, {name}, \"PX{}__Ri\");\n",
            cell_abstract(library)
        ));
    }
    out.push_str(&later::hl_adapter(library));
    out.push_str(&format!(
        "\n// What the library's values hold that the VM's collector cannot see, and\n// whether the library asked for a collection since the last call.\n#[unsafe(no_mangle)]\npub extern \"C\" fn {held}() -> f64 {{\n    memory::held() as f64\n}}\ndefine_prim!(hlp_memory_held, {held}, \"P_d\");\n\n#[unsafe(no_mangle)]\npub extern \"C\" fn {wanted}() -> bool {{\n    memory::take_request()\n}}\ndefine_prim!(hlp_memory_wanted, {wanted}, \"P_b\");\n",
        held = held_export(library),
        wanted = wanted_export(library),
    ));
    out
}
