//! The two Rust adapters: one over the plain C ABI, for hxcpp, and one of
//! HashLink primitives. Each is the text of a file a thin crate includes.

use crate::model::{Interface, Library, Method, Param, Receiver, Type};
use crate::names::{
    abstract_name, cell_abstract, cell_export, export, has_receiver, held_export, local, release,
    wanted_export,
};

const HEADER: &str = "// Generated by hxn-gen from the library's source. Do not edit.\n";

fn question(method: &Method) -> &'static str {
    if method.fallible { "?" } else { "" }
}

// `this.add(amount)` or `Counter::live()`.
fn call(interface: &Interface, method: &Method, arguments: &[String]) -> String {
    let target = if has_receiver(method) {
        format!("this.{}", method.name)
    } else {
        format!("{}::{}", interface.name, method.name)
    };
    format!("{target}({}){}", arguments.join(", "), question(method))
}

// The receiver as `this`, borrowed or taken from what `open` yields: a
// `Result` of the handle behind the pointer.
fn receiver(method: &Method, open: &str) -> Option<String> {
    match method.receiver {
        Receiver::None => None,
        Receiver::Shared => Some(format!("let this = {open}?.borrow()?;")),
        Receiver::Exclusive => Some(format!("let mut this = {open}?.borrow_mut()?;")),
        // Taken out, so the Haxe object is closed whatever the call does.
        Receiver::Owned => Some(format!("let this = {open}?.take()?.ok_or(Fault::Closed)?;")),
    }
}

// A borrowed interface: the statement that borrows it, and the argument.
// `open` turns the parameter's name into a `Result` of its handle.
fn borrowed(param: &Param, nullable: bool, open: impl Fn(&str) -> String) -> (String, String) {
    let name = &param.name;
    let (borrow, mutable) = if param.exclusive {
        ("borrow_mut", "mut ")
    } else {
        ("borrow", "")
    };
    let opened = open(name);
    if nullable {
        let argument = if param.exclusive {
            format!("{name}.as_deref_mut()")
        } else {
            format!("{name}.as_deref()")
        };
        (
            format!(
                "let {mutable}{name} = if {name}.is_null() {{ None }} else {{ Some({opened}?.{borrow}()?) }};"
            ),
            argument,
        )
    } else {
        let pass = if param.exclusive { "&mut " } else { "&" };
        (
            format!("let {mutable}{name} = {opened}?.{borrow}()?;"),
            format!("{pass}{name}"),
        )
    }
}

// A cell the host lent: the statement that turns its address into a
// reference, refusing a null one, and the argument.
fn lent(param: &Param) -> (String, String) {
    let name = &param.name;
    let ty = if param.ty == Type::AtomicBool {
        "AtomicFlag"
    } else {
        "AtomicI32"
    };
    (
        format!(
            "let {name} = if {name}.is_null() {{ return Err(Fault::Null.into()); }} else {{ {ty}::from_ptr({name}) }};"
        ),
        name.clone(),
    )
}

fn c_method(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut params = Vec::new();
    let mut body = Vec::new();
    if let Some(this) = receiver(
        method,
        &format!("Handle::<{}>::from_raw(this)", interface.name),
    ) {
        params.push(String::from("this: RawHandle"));
        body.push(this);
    }
    let mut arguments = Vec::new();
    for param in &method.params {
        let name = &param.name;
        let (ty, argument) = match &param.ty {
            // An int at the boundary: C has no one size for a bool.
            Type::Bool => ("i32", format!("{name} != 0")),
            Type::I32 => ("i32", name.clone()),
            Type::F64 => ("f64", name.clone()),
            Type::Str => ("Slice<'_>", format!("{name}.as_str()?")),
            Type::Bytes => ("Slice<'_>", format!("{name}.as_bytes()?")),
            Type::Handle {
                interface,
                nullable,
            } => {
                let (statement, argument) = borrowed(param, *nullable, |name| {
                    format!("Handle::<{interface}>::from_raw({name})")
                });
                body.push(statement);
                ("RawHandle", argument)
            }
            Type::AtomicInt | Type::AtomicBool => {
                let (statement, argument) = lent(param);
                body.push(statement);
                ("*mut i32", argument)
            }
            Type::Void => unreachable!("not a parameter type"),
        };
        params.push(format!("{name}: {ty}"));
        arguments.push(argument);
    }
    let call = call(interface, method, &arguments);
    let (out, result) = match &method.returns {
        Type::Void => (None, format!("{call};\n            Ok(())")),
        Type::Bool => (Some("i32"), format!("Ok(i32::from({call}))")),
        Type::I32 => (Some("i32"), format!("Ok({call})")),
        Type::F64 => (Some("f64"), format!("Ok({call})")),
        Type::Str => (Some("Buf"), format!("Ok(Buf::from({call}))")),
        Type::Handle {
            nullable: false, ..
        } => (Some("RawHandle"), format!("Ok(Handle::into_raw({call}))")),
        Type::Handle { nullable: true, .. } => (
            Some("RawHandle"),
            format!("Ok({call}.map_or(null_mut(), Handle::into_raw))"),
        ),
        // Handed over as the integer cell both kinds are, with the handle
        // keeping it alive.
        Type::AtomicInt => (Some("RawHandle"), format!("Ok(Handle::into_raw({call}))")),
        Type::AtomicBool => (
            Some("RawHandle"),
            format!("Ok(Handle::into_raw(AtomicFlag::into_int({call})))"),
        ),
        Type::Bytes => unreachable!("not a result type"),
    };
    let out_argument = match out {
        Some(ty) => {
            params.push(format!("out: *mut {ty}"));
            "out"
        }
        None => "null_mut::<()>()",
    };
    params.push(String::from("err: *mut Buf"));
    body.push(result);
    format!(
        "#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({params}) -> Status {{\n    unsafe {{\n        guard({out_argument}, err, || {{\n            {body}\n        }})\n    }}\n}}\n",
        name = export(library, &interface.name, &method.name),
        params = params.join(", "),
        body = body.join("\n            "),
    )
}

fn imports(library: &Library, core: &str) -> String {
    let names: Vec<&str> = library
        .interfaces
        .iter()
        .map(|interface| interface.name.as_str())
        .collect();
    match names.as_slice() {
        [] => String::new(),
        [name] => format!("use {core}::{name};\n"),
        names => format!("use {core}::{{{}}};\n", names.join(", ")),
    }
}

/// The adapter over the plain C ABI. `core` is the path the library's items
/// are found under, such as `counter_core`.
pub fn c_adapter(library: &Library, core: &str) -> String {
    let mut out = String::from(HEADER);
    out.push_str("\n#[allow(unused_imports)]\nuse std::ptr::null_mut;\n");
    out.push_str("#[allow(unused_imports)]\nuse std::sync::Arc;\n");
    out.push_str("#[allow(unused_imports)]\nuse std::sync::atomic::AtomicI32;\n\n");
    out.push_str(
        "#[allow(unused_imports)]\nuse hxn_abi::{AtomicFlag, Buf, Fault, Handle, RawHandle, Slice, Status, guard, memory, release};\n",
    );
    out.push_str(&imports(library, core));
    for interface in &library.interfaces {
        for method in &interface.methods {
            out.push('\n');
            out.push_str(&c_method(library, interface, method));
        }
        out.push_str(&format!(
            "\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}(this: RawHandle, err: *mut Buf) -> Status {{\n    unsafe {{\n        guard(null_mut::<()>(), err, || {{\n            Handle::<{interface}>::from_raw(this)?.take()?;\n            Ok(())\n        }})\n    }}\n}}\n",
            name = export(library, &interface.name, "close"),
            interface = interface.name,
        ));
    }
    if library.returns_cells() {
        out.push_str(&format!(
            "\n// Where a cell the library handed over is, for the host's own atomic operations.\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}(this: RawHandle, out: *mut *mut i32, err: *mut Buf) -> Status {{\n    unsafe {{\n        guard(out, err, || {{\n            Ok(Handle::<Arc<AtomicI32>>::from_raw(this)?.borrow()?.as_ptr())\n        }})\n    }}\n}}\n",
            cell_export(library)
        ));
    }
    out.push_str(&format!(
        "\n// What the library's values hold that the host's collector cannot see, and\n// whether the library asked for a collection since the last call.\n#[unsafe(no_mangle)]\npub extern \"C\" fn {held}() -> f64 {{\n    memory::held() as f64\n}}\n\n#[unsafe(no_mangle)]\npub extern \"C\" fn {wanted}() -> i32 {{\n    i32::from(memory::take_request())\n}}\n",
        held = held_export(library),
        wanted = wanted_export(library),
    ));
    out.push_str(&format!(
        "\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}(this: RawHandle) {{\n    unsafe {{ release(this) }}\n}}\n",
        release(library)
    ));
    out
}

fn hl_letter(library: &Library, ty: &Type) -> String {
    match ty {
        Type::Void => String::from("v"),
        Type::Bool => String::from("b"),
        Type::I32 => String::from("i"),
        Type::F64 => String::from("d"),
        // A result: UTF-16 bytes for `String.fromUCS2`.
        Type::Str => String::from("B"),
        Type::Handle { interface, .. } => format!("X{}_", abstract_name(library, interface)),
        Type::AtomicInt | Type::AtomicBool => format!("X{}_", cell_abstract(library)),
        Type::Bytes => unreachable!("not a result type"),
    }
}

fn hl_method(library: &Library, interface: &Interface, method: &Method) -> String {
    let own = abstract_name(library, &interface.name);
    let mut params = Vec::new();
    let mut signature = String::new();
    let mut body = Vec::new();
    if let Some(this) = receiver(method, &format!("handle::<{}>(this)", interface.name)) {
        params.push(String::from("this: *mut Managed"));
        signature.push_str(&format!("X{own}_"));
        body.push(this);
    }
    let mut arguments = Vec::new();
    for param in &method.params {
        let name = &param.name;
        match &param.ty {
            Type::Bool => {
                params.push(format!("{name}: bool"));
                signature.push('b');
                arguments.push(name.clone());
            }
            Type::I32 => {
                params.push(format!("{name}: i32"));
                signature.push('i');
                arguments.push(name.clone());
            }
            Type::F64 => {
                params.push(format!("{name}: f64"));
                signature.push('d');
                arguments.push(name.clone());
            }
            Type::Str => {
                params.push(format!("{name}: *mut vstring"));
                signature.push_str("OBi_");
                body.push(format!("let {name} = string({name})?.unwrap_or_default();"));
                arguments.push(format!("&{name}"));
            }
            Type::Bytes => {
                params.push(format!("{name}: *mut vbyte"));
                params.push(format!("{name}_length: i32"));
                signature.push_str("Bi");
                body.push(format!(
                    "let {name} = slice({name}, {name}_length).as_bytes()?;"
                ));
                arguments.push(name.clone());
            }
            Type::Handle {
                interface,
                nullable,
            } => {
                params.push(format!("{name}: *mut Managed"));
                signature.push_str(&hl_letter(library, &param.ty));
                let (statement, argument) = borrowed(param, *nullable, |name| {
                    format!("handle::<{interface}>({name})")
                });
                body.push(statement);
                arguments.push(argument);
            }
            Type::AtomicInt | Type::AtomicBool => {
                params.push(format!("{name}: *mut i32"));
                // A reference to an int, which is what the VM's own atomic
                // operations take.
                signature.push_str("Ri");
                let (statement, argument) = lent(param);
                body.push(statement);
                arguments.push(argument);
            }
            Type::Void => unreachable!("not a parameter type"),
        }
    }
    let mut call = call(interface, method, &arguments);
    if method.blocking {
        // Everything the call reads was copied or borrowed above.
        let inner = call.trim_end_matches('?').to_owned();
        call = format!("blocking(|| {inner}){}", question(method));
    }
    let (ty, result) = match &method.returns {
        Type::Void => ("()", format!("{call};\n            Ok(())")),
        Type::Bool => ("bool", format!("Ok({call})")),
        Type::I32 => ("i32", format!("Ok({call})")),
        Type::F64 => ("f64", format!("Ok({call})")),
        Type::Str => ("*mut vbyte", format!("Ok(utf16(&{call}))")),
        Type::Handle {
            nullable: false, ..
        } => ("*mut Managed", format!("Ok(manage({call}))")),
        Type::Handle { nullable: true, .. } => (
            "*mut Managed",
            format!("Ok({call}.map_or(null_mut(), manage))"),
        ),
        Type::AtomicInt => ("*mut Managed", format!("Ok(manage({call}))")),
        Type::AtomicBool => (
            "*mut Managed",
            format!("Ok(manage(AtomicFlag::into_int({call})))"),
        ),
        Type::Bytes => unreachable!("not a result type"),
    };
    body.push(result);
    let name = export(library, &interface.name, &method.name);
    let returns = if ty == "()" {
        String::new()
    } else {
        format!(" -> {ty}")
    };
    format!(
        "#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({params}){returns} {{\n    unsafe {{\n        prim(|| {{\n            {body}\n        }})\n    }}\n}}\ndefine_prim!(hlp_{local}, {name}, \"P{signature}_{ret}\");\n",
        params = params.join(", "),
        body = body.join("\n            "),
        local = local(&interface.name, &method.name),
        ret = hl_letter(library, &method.returns),
    )
}

/// The adapter of HashLink primitives, for an `.hdll` or a wasm side module.
pub fn hl_adapter(library: &Library, core: &str) -> String {
    let mut out = String::from(HEADER);
    out.push_str("\n#[allow(unused_imports)]\nuse std::ptr::null_mut;\n\n");
    out.push_str("#[allow(unused_imports)]\nuse std::sync::Arc;\n");
    out.push_str("#[allow(unused_imports)]\nuse std::sync::atomic::AtomicI32;\n\n");
    out.push_str("#[allow(unused_imports)]\nuse hl_abi::{vbyte, vstring};\n");
    out.push_str("#[allow(unused_imports)]\nuse hxn_abi::{AtomicFlag, Fault, memory};\n");
    out.push_str(
        "#[allow(unused_imports)]\nuse hxn_hl::{Managed, blocking, define_prim, handle, manage, prim, slice, string, utf16};\n",
    );
    out.push_str(&imports(library, core));
    for interface in &library.interfaces {
        let own = abstract_name(library, &interface.name);
        for method in &interface.methods {
            out.push('\n');
            out.push_str(&hl_method(library, interface, method));
        }
        let name = export(library, &interface.name, "close");
        out.push_str(&format!(
            "\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}(this: *mut Managed) {{\n    unsafe {{\n        prim(|| {{\n            handle::<{interface}>(this)?.take()?;\n            Ok(())\n        }})\n    }}\n}}\ndefine_prim!(hlp_{local}, {name}, \"PX{own}__v\");\n",
            interface = interface.name,
            local = local(&interface.name, "close"),
        ));
    }
    if library.returns_cells() {
        let name = cell_export(library);
        out.push_str(&format!(
            "\n// Where a cell the library handed over is, for the VM's own atomic operations.\n#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}(this: *mut Managed) -> *mut i32 {{\n    unsafe {{ prim(|| Ok(handle::<Arc<AtomicI32>>(this)?.borrow()?.as_ptr())) }}\n}}\ndefine_prim!(hlp_atomic_cell, {name}, \"PX{}__Ri\");\n",
            cell_abstract(library)
        ));
    }
    out.push_str(&format!(
        "\n// What the library's values hold that the VM's collector cannot see, and\n// whether the library asked for a collection since the last call.\n#[unsafe(no_mangle)]\npub extern \"C\" fn {held}() -> f64 {{\n    memory::held() as f64\n}}\ndefine_prim!(hlp_memory_held, {held}, \"P_d\");\n\n#[unsafe(no_mangle)]\npub extern \"C\" fn {wanted}() -> bool {{\n    memory::take_request()\n}}\ndefine_prim!(hlp_memory_wanted, {wanted}, \"P_b\");\n",
        held = held_export(library),
        wanted = wanted_export(library),
    ));
    out
}
