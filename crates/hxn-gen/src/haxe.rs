//! The Haxe classes: one module an interface, written once for HashLink and
//! once for hxcpp, with the same public API.
//!
//! A class owns one handle. A value the library returns is adopted by a new
//! object of its interface's class, which is how a result of another
//! interface, or of a function other than `new`, gets an owner.

use crate::later;
use crate::lent;
use crate::model::{Interface, Library, Method, Type};
use crate::names::{
    abstract_name, camel, cell_abstract, cell_class, has_receiver, local, memory_class,
    native_class, weak_abstract, weak_class,
};

/// A generated file: its path relative to a class path, and its text.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct File {
    pub path: String,
    pub text: String,
}

const HEADER: &str = "// Generated by hxn-gen from the library's source. Do not edit.\n";

fn haxe_type(ty: &Type) -> String {
    match ty {
        Type::Void => String::from("Void"),
        Type::Bool => String::from("Bool"),
        Type::I32 => String::from("Int"),
        Type::F64 => String::from("Float"),
        Type::Str => String::from("String"),
        Type::Bytes => String::from("haxe.io.Bytes"),
        Type::Future(of) => format!("hxn.Future<{}>", haxe_type(of)),
        Type::Stream(of) => format!("hxn.Stream<{}>", haxe_type(of)),
        Type::Signal(of) => format!("hxn.Signal<{}>", haxe_type(of)),
        Type::Lent { params, returns } => lent::haxe_type(params, returns),
        Type::AtomicInt => String::from("hxn.AtomicInt"),
        Type::AtomicBool => String::from("hxn.AtomicBool"),
        Type::Handle {
            interface,
            nullable: false,
        } => interface.clone(),
        Type::Handle {
            interface,
            nullable: true,
        } => format!("Null<{interface}>"),
    }
}

fn docs(lines: &[String], indent: &str) -> String {
    match lines {
        [] => String::new(),
        [line] => format!("{indent}/** {line} **/\n"),
        lines => {
            let mut out = format!("{indent}/**\n");
            for line in lines {
                out.push_str(&format!("{indent}\t{line}\n"));
            }
            out.push_str(&format!("{indent}**/\n"));
            out
        }
    }
}

fn params(method: &Method) -> String {
    let params: Vec<String> = method
        .params
        .iter()
        .map(|param| format!("{}:{}", camel(&param.name), haxe_type(&param.ty)))
        .collect();
    params.join(", ")
}

// `public function add(amount:Int):Int`, or the constructor's.
fn signature(method: &Method) -> String {
    if method.constructor {
        return format!("\tpublic function new({})", params(method));
    }
    let modifier = if has_receiver(method) { "" } else { "static " };
    format!(
        "\tpublic {modifier}function {}({}):{}",
        camel(&method.name),
        params(method),
        haxe_type(&method.returns)
    )
}

const CLOSE_DOCS: &str = "\t/**\n\t\tReleases the native value now. The collector does it otherwise. Using\n\t\tthis object afterwards throws.\n\t**/\n";

const SHARED_CLOSE_DOCS: &str = "\t/**\n\t\tGives up this object's share of the value now. The collector does it\n\t\totherwise. The value lives while anything else holds a share. Using\n\t\tthis object afterwards throws.\n\t**/\n";

const SAME_DOCS: &str = "\t/**\n\t\tWhether `other` holds the value this does. Two objects can: each time\n\t\tthe library returns the value, a new object gets a share of it.\n\t**/\n";

const WEAK_DOCS: &str = "\t/** A reference to the value that does not keep it alive. **/\n";

const UPGRADE_DOCS: &str =
    "\t/** The value, if anything still holds it: a new object with a share of its own. **/\n";

fn close_docs(interface: &Interface) -> &'static str {
    if interface.shared {
        SHARED_CLOSE_DOCS
    } else {
        CLOSE_DOCS
    }
}

// The library's meter, held by every class so that it exists whichever of
// them a program uses.
fn meter(library: &Library) -> String {
    format!(
        "\t@:noCompletion static final memory = {}.meter;\n",
        memory_class(library)
    )
}

// What HashLink knows `interface`'s values as, named from `module`.
fn hl_raw(interface: &str, module: &str) -> String {
    if interface == module {
        format!("{interface}Raw")
    } else {
        format!("{interface}.{interface}Raw")
    }
}

fn hl_native(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut params = Vec::new();
    if has_receiver(method) {
        params.push(format!("self:{}", hl_raw(&interface.name, &interface.name)));
    }
    for param in &method.params {
        let name = camel(&param.name);
        match &param.ty {
            Type::Bool => params.push(format!("{name}:Bool")),
            Type::I32 => params.push(format!("{name}:Int")),
            Type::F64 => params.push(format!("{name}:Float")),
            Type::Str => params.push(format!("{name}:String")),
            Type::Bytes => {
                params.push(format!("{name}:hl.Bytes"));
                params.push(format!("{name}Length:Int"));
            }
            Type::Handle { interface: of, .. } => {
                params.push(format!("{name}:{}", hl_raw(of, &interface.name)));
            }
            Type::AtomicInt | Type::AtomicBool => params.push(format!("{name}:hl.Ref<Int>")),
            // The wrapper the binding makes, not the function the user passed.
            Type::Lent {
                params: taken,
                returns,
            } => params.push(format!("{name}:{}", lent::haxe_native_type(taken, returns))),
            Type::Void | Type::Future(_) | Type::Stream(_) | Type::Signal(_) => {
                unreachable!("not a parameter type")
            }
        }
    }
    if method.returns == Type::Bytes {
        // Where the library writes how many bytes it returned.
        params.push(String::from("out:hl.Ref<Int>"));
    }
    let (ty, body) = match &method.returns {
        Type::Void => (String::from("Void"), "{}"),
        Type::Bool => (String::from("Bool"), "\n\t\treturn false;"),
        Type::I32 => (String::from("Int"), "\n\t\treturn 0;"),
        Type::F64 => (String::from("Float"), "\n\t\treturn 0.;"),
        Type::Str | Type::Bytes => (String::from("hl.Bytes"), "\n\t\treturn null;"),
        Type::Lent { .. } => unreachable!("not a result type"),
        Type::Handle { interface: of, .. } => (hl_raw(of, &interface.name), "\n\t\treturn null;"),
        Type::AtomicInt | Type::AtomicBool => (String::from("CellRaw"), "\n\t\treturn null;"),
        Type::Future(_) | Type::Stream(_) | Type::Signal(_) => {
            let (kind, _) = later::of(&method.returns).expect("a result over time");
            let class = later::class(library, kind);
            (format!("{class}.{class}Raw"), "\n\t\treturn null;")
        }
    };
    let separator = if body == "{}" { " " } else { "" };
    format!(
        "\tpublic static function {}({}):{ty}{separator}{body}\n",
        local(&interface.name, &method.name),
        params.join(", ")
    )
}

// A method's body from its statements. One that lends functions makes its
// native call inside `hxn.Callback.during`, which throws what a lent
// function threw once the library has returned.
fn body(guards: &[String], lines: &[String]) -> String {
    let block = |lines: &[String]| {
        let mut out = String::from(" {\n");
        for line in lines {
            out.push_str(&format!("\t\t{line}\n"));
        }
        out.push_str("\t}\n");
        out
    };
    if guards.is_empty() {
        return match lines {
            [only] => format!("\n\t\t{only}\n"),
            lines => block(lines),
        };
    }
    let returns = lines.last().is_some_and(|line| line.starts_with("return "));
    let mut all = guards.to_vec();
    all.push(format!(
        "{}hxn.Callback.during(() -> {{",
        if returns { "return " } else { "" }
    ));
    for line in lines {
        all.push(format!("\t{}", line.replace('\n', "\n\t")));
    }
    if !returns {
        all.push(String::from("\treturn true;"));
    }
    all.push(String::from("});"));
    block(&all)
}

fn hl_method(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut guards = Vec::new();
    let mut arguments = Vec::new();
    if has_receiver(method) {
        arguments.push(String::from("raw"));
    }
    for param in &method.params {
        let name = camel(&param.name);
        match &param.ty {
            Type::Bytes => {
                arguments.push(name.clone());
                arguments.push(format!("{name}.length"));
            }
            // Null goes through as null whether or not the library takes
            // one: it is the library that says so, the same on every runtime.
            Type::Handle { .. } => {
                arguments.push(format!("{name} == null ? null : {name}.raw"));
            }
            Type::AtomicInt | Type::AtomicBool => {
                arguments.push(format!("{name} == null ? null : {name}.pointer"));
            }
            Type::Lent { params, returns } => {
                guards.push(lent::haxe_guard(&name, params, returns));
                arguments.push(lent::guarded(&name));
            }
            _ => arguments.push(name),
        }
    }
    if method.returns == Type::Bytes {
        arguments.push(String::from("outLength"));
    }
    let call = format!(
        "Native.{}({})",
        local(&interface.name, &method.name),
        arguments.join(", ")
    );
    let mut lines = Vec::new();
    if method.constructor {
        lines.push(format!("raw = {call};"));
        if interface.weighed {
            lines.push(String::from("memory.check();"));
        }
    } else {
        match &method.returns {
            Type::Void => lines.push(format!("{call};")),
            Type::Str => lines.push(format!("return @:privateAccess String.fromUCS2({call});")),
            Type::Bytes => {
                lines.push(String::from("var outLength = 0;"));
                lines.push(format!("var data = {call};"));
                lines.push(String::from(
                    "return @:privateAccess new haxe.io.Bytes(data, outLength);",
                ));
            }
            Type::Handle {
                interface: of,
                nullable: false,
            } => lines.push(format!("return {of}.adopt({call});")),
            Type::Handle {
                interface: of,
                nullable: true,
            } => {
                lines.push(format!("var made = {call};"));
                lines.push(format!("return made == null ? null : {of}.adopt(made);"));
            }
            Type::Future(_) | Type::Stream(_) | Type::Signal(_) => {
                let (kind, carried) = later::of(&method.returns).expect("a result over time");
                lines.push(format!(
                    "return {}.{}({call});",
                    later::class(library, kind),
                    later::maker(carried)
                ));
            }
            // The cell lives in the library; what it handed over keeps it
            // alive for as long as the atomic is referenced.
            Type::AtomicInt => {
                lines.push(format!("var owner = {call};"));
                lines.push(String::from(
                    "return hxn.AtomicInt.over(Native.atomic_cell(owner), () -> owner);",
                ));
            }
            Type::AtomicBool => {
                lines.push(format!("var owner = {call};"));
                lines.push(String::from(
                    "return hxn.AtomicBool.over(hxn.AtomicInt.over(Native.atomic_cell(owner), () -> owner));",
                ));
            }
            _ => lines.push(format!("return {call};")),
        }
    }
    let mut out = docs(&method.docs, "\t");
    out.push_str(&signature(method));
    out.push_str(&body(&guards, &lines));
    out
}

fn hl_module(library: &Library, interface: &Interface) -> String {
    let name = &interface.name;
    let cells = interface
        .methods
        .iter()
        .any(|method| matches!(method.returns, Type::AtomicInt | Type::AtomicBool));
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "@:noCompletion typedef {name}Raw = hl.Abstract<\"{}\">;\n",
        abstract_name(library, name)
    ));
    if cells {
        out.push_str(&format!(
            "private typedef CellRaw = hl.Abstract<\"{}\">;\n",
            cell_abstract(library)
        ));
    }
    out.push_str(&format!(
        "\n@:hlNative(\"{}\")\nprivate class Native {{\n",
        library.name
    ));
    for method in &interface.methods {
        out.push_str(&hl_native(library, interface, method));
        out.push('\n');
    }
    if cells {
        out.push_str(
            "\tpublic static function atomic_cell(self:CellRaw):hl.Ref<Int>\n\t\treturn null;\n\n",
        );
    }
    if interface.shared {
        out.push_str(&format!(
            "\tpublic static function {same}(self:{name}Raw, other:{name}Raw):Bool\n\t\treturn false;\n\n\tpublic static function {weak}(self:{name}Raw):{weak_raw}\n\t\treturn null;\n\n",
            same = local(name, "same"),
            weak = local(name, "weak"),
            weak_raw = hl_raw(&weak_class(name), name),
        ));
    }
    out.push_str(&format!(
        "\tpublic static function {}(self:{name}Raw):Void {{}}\n}}\n\n",
        local(name, "close")
    ));
    out.push_str(&docs(&interface.docs, ""));
    let check = if interface.weighed {
        "\t\tmemory.check();\n"
    } else {
        ""
    };
    out.push_str(&format!(
        "class {name} {{\n\t@:noCompletion public var raw:{name}Raw;\n{meter}\n\t/** An object for a value the library returned. **/\n\t@:noCompletion public static function adopt(raw:{name}Raw):{name} {{\n\t\tvar made:{name} = Type.createEmptyInstance({name});\n\t\tmade.raw = raw;\n{check}\t\treturn made;\n\t}}\n",
        meter = meter(library),
    ));
    for method in &interface.methods {
        out.push('\n');
        out.push_str(&hl_method(library, interface, method));
    }
    if interface.shared {
        out.push_str(&format!(
            "\n{SAME_DOCS}\tpublic function same(other:Null<{name}>):Bool\n\t\treturn Native.{same}(raw, other == null ? null : other.raw);\n\n{WEAK_DOCS}\tpublic function weak():{weak_class}\n\t\treturn {weak_class}.adopt(Native.{weak}(raw));\n",
            same = local(name, "same"),
            weak = local(name, "weak"),
            weak_class = weak_class(name),
        ));
    }
    out.push_str(&format!(
        "\n{}\tpublic function close():Void\n\t\tNative.{}(raw);\n}}\n",
        close_docs(interface),
        local(name, "close")
    ));
    out
}

// The weak reference to a shared interface's value: a class of its own.
fn hl_weak(library: &Library, interface: &Interface) -> String {
    let of = &interface.name;
    let name = weak_class(of);
    format!(
        "{HEADER}@:noCompletion typedef {name}Raw = hl.Abstract<\"{weak_abstract}\">;\n\n@:hlNative(\"{library}\")\nprivate class Native {{\n\tpublic static function {upgrade}(self:{name}Raw):{of}.{of}Raw\n\t\treturn null;\n\n\tpublic static function {close}(self:{name}Raw):Void {{}}\n}}\n\n/** A reference to a `{of}` that does not keep it alive. **/\nclass {name} {{\n\t@:noCompletion public var raw:{name}Raw;\n\n\t@:noCompletion public static function adopt(raw:{name}Raw):{name} {{\n\t\tvar made:{name} = Type.createEmptyInstance({name});\n\t\tmade.raw = raw;\n\t\treturn made;\n\t}}\n\n{UPGRADE_DOCS}\tpublic function upgrade():Null<{of}> {{\n\t\tvar made = Native.{upgrade}(raw);\n\t\treturn made == null ? null : {of}.adopt(made);\n\t}}\n\n\t/** Releases the reference now. The collector does it otherwise. **/\n\tpublic function close():Void\n\t\tNative.{close}(raw);\n}}\n",
        library = library.name,
        weak_abstract = weak_abstract(library, of),
        upgrade = local(of, "weak_upgrade"),
        close = local(of, "weak_close"),
    )
}

fn cpp_weak(library: &Library, interface: &Interface) -> String {
    let of = &interface.name;
    let name = weak_class(of);
    format!(
        "{HEADER}/** A reference to a `{of}` that does not keep it alive. **/\nclass {name} {{\n\t@:noCompletion @:unreflective public var raw:cpp.RawPointer<cpp.Void>;\n\n\t// Runs inside a collection: it may free, and may not touch the Haxe heap.\n\tstatic function finalize(self:{name}):Void {{\n\t\t{native}.release(self.raw);\n\t}}\n\n\t@:noCompletion public static function adopt():{name}\n\t\treturn Type.createEmptyInstance({name});\n\n\t@:noCompletion public function own():Void\n\t\tcpp.vm.Gc.setFinalizer(this, cpp.Function.fromStaticFunction(finalize));\n\n{UPGRADE_DOCS}\tpublic function upgrade():Null<{of}> {{\n\t\tvar made = {of}.adopt();\n\t\tmade.raw = {native}.{upgrade}(raw);\n\t\tif (made.raw == null)\n\t\t\treturn null;\n\t\tmade.own();\n\t\treturn made;\n\t}}\n\n\t/** Releases the reference now. The collector does it otherwise. **/\n\tpublic function close():Void\n\t\t{native}.{close}(raw);\n}}\n",
        native = native_class(library),
        upgrade = local(of, "weak_upgrade"),
        close = local(of, "weak_close"),
    )
}

fn cpp_method(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut guards = Vec::new();
    let mut before = Vec::new();
    let mut arguments = Vec::new();
    if has_receiver(method) {
        arguments.push(String::from("raw"));
    }
    for param in &method.params {
        let name = camel(&param.name);
        match &param.ty {
            Type::Bytes => arguments.push(format!("{name}.getData()")),
            // Null goes through as null whether or not the library takes
            // one. hxcpp does not check a null object before reading its field.
            Type::Handle { .. } => {
                before.push(format!("var {name}Raw:cpp.RawPointer<cpp.Void> = null;"));
                before.push(format!(
                    "if ({name} != null)\n\t\t\t{name}Raw = {name}.raw;"
                ));
                arguments.push(format!("{name}Raw"));
            }
            Type::AtomicInt | Type::AtomicBool => {
                before.push(format!("var {name}Raw:cpp.RawPointer<Int> = null;"));
                before.push(format!(
                    "if ({name} != null)\n\t\t\t{name}Raw = {name}.pointer.raw;"
                ));
                arguments.push(format!("{name}Raw"));
            }
            Type::Lent { params, returns } => {
                guards.push(lent::haxe_guard(&name, params, returns));
                arguments.push(lent::guarded(&name));
            }
            _ => arguments.push(name),
        }
    }
    let call = format!(
        "{}.{}({})",
        native_class(library),
        local(&interface.name, &method.name),
        arguments.join(", ")
    );

    let mut body = before;
    if method.constructor {
        body.push(format!("raw = {call};"));
        body.push(String::from("own();"));
    } else {
        match &method.returns {
            Type::Void => body.push(format!("{call};")),
            Type::Handle {
                interface: of,
                nullable,
            } => {
                // Owned only once the library has handed the value over.
                body.push(format!("var made = {of}.adopt();"));
                body.push(format!("made.raw = {call};"));
                if *nullable {
                    body.push(String::from("if (made.raw == null)\n\t\t\treturn null;"));
                }
                body.push(String::from("made.own();"));
                body.push(String::from("return made;"));
            }
            Type::AtomicInt | Type::AtomicBool => {
                // The cell lives in the library; its owner keeps it alive for
                // as long as the atomic is referenced.
                body.push(format!("var owner = {}.adopt();", cell_class(library)));
                body.push(format!("owner.raw = {call};"));
                body.push(String::from("owner.own();"));
                body.push(if method.returns == Type::AtomicBool {
                    String::from("return hxn.AtomicBool.over(owner.cell());")
                } else {
                    String::from("return owner.cell();")
                });
            }
            Type::Future(_) | Type::Stream(_) | Type::Signal(_) => {
                let (kind, carried) = later::of(&method.returns).expect("a result over time");
                // Owned only once the library has handed it over.
                body.push(format!(
                    "var made = {}.adopt();",
                    later::class(library, kind)
                ));
                body.push(format!("made.raw = {call};"));
                body.push(String::from("made.own();"));
                body.push(format!("return made.{}();", later::maker(carried)));
            }
            Type::Bytes => {
                body.push(format!("return haxe.io.Bytes.ofData({call});"));
            }
            _ => body.push(format!("return {call};")),
        }
    }
    let mut out = docs(&method.docs, "\t");
    out.push_str(&signature(method));
    out.push_str(&self::body(&guards, &body));
    out
}

fn cpp_module(library: &Library, interface: &Interface) -> String {
    let name = &interface.name;
    let native = native_class(library);
    let mut out = String::from(HEADER);
    out.push_str(&docs(&interface.docs, ""));
    // A weighed object is counted from the moment it owns its value.
    let own = if interface.weighed {
        " {\n\t\tcpp.vm.Gc.setFinalizer(this, cpp.Function.fromStaticFunction(finalize));\n\t\tmemory.check();\n\t}\n"
    } else {
        "\n\t\tcpp.vm.Gc.setFinalizer(this, cpp.Function.fromStaticFunction(finalize));\n"
    };
    out.push_str(&format!(
        "class {name} {{\n\t@:noCompletion @:unreflective public var raw:cpp.RawPointer<cpp.Void>;\n{meter}\n\t// Runs inside a collection: it may free, and may not touch the Haxe heap.\n\tstatic function finalize(self:{name}):Void {{\n\t\t{native}.release(self.raw);\n\t}}\n\n\t/** An object that owns nothing yet: its maker sets `raw`, then calls `own`. **/\n\t@:noCompletion public static function adopt():{name}\n\t\treturn Type.createEmptyInstance({name});\n\n\t/** Has the collector release the value this now holds. **/\n\t@:noCompletion public function own():Void{own}",
        meter = meter(library),
    ));
    for method in &interface.methods {
        out.push('\n');
        out.push_str(&cpp_method(library, interface, method));
    }
    if interface.shared {
        out.push_str(&format!(
            "\n{SAME_DOCS}\tpublic function same(other:Null<{name}>):Bool {{\n\t\tvar otherRaw:cpp.RawPointer<cpp.Void> = null;\n\t\tif (other != null)\n\t\t\totherRaw = other.raw;\n\t\treturn {native}.{same}(raw, otherRaw);\n\t}}\n\n{WEAK_DOCS}\tpublic function weak():{weak_class} {{\n\t\tvar made = {weak_class}.adopt();\n\t\tmade.raw = {native}.{weak}(raw);\n\t\tmade.own();\n\t\treturn made;\n\t}}\n",
            same = local(name, "same"),
            weak = local(name, "weak"),
            weak_class = weak_class(name),
        ));
    }
    out.push_str(&format!(
        "\n{}\tpublic function close():Void\n\t\t{native}.{}(raw);\n}}\n",
        close_docs(interface),
        local(name, "close")
    ));
    out
}

/// The classes for HashLink, one file an interface.
pub fn haxe_hl(library: &Library) -> Vec<File> {
    let mut files: Vec<File> = library
        .interfaces
        .iter()
        .map(|interface| File {
            path: format!("{}.hx", interface.name),
            text: hl_module(library, interface),
        })
        .collect();
    for interface in library.interfaces.iter().filter(|i| i.shared) {
        files.push(File {
            path: format!("{}.hx", weak_class(&interface.name)),
            text: hl_weak(library, interface),
        });
    }
    files.extend(later::hl_files(library));
    files.push(File {
        path: format!("{}.hx", memory_class(library)),
        text: hl_memory(library),
    });
    files
}

const MEMORY_DOCS: &str = "What the library's values hold that the collector cannot see. A weighed\n\tobject checks it when it is made, and a delivery does.";

fn hl_memory(library: &Library) -> String {
    format!(
        "{HEADER}@:hlNative(\"{library}\")\nprivate class Native {{\n\tpublic static function memory_held():Float\n\t\treturn 0.;\n\n\tpublic static function memory_wanted():Bool\n\t\treturn false;\n}}\n\n/**\n\t{MEMORY_DOCS}\n**/\nclass {name} {{\n\tpublic static final meter = new hxn.Gc.Meter(() -> Native.memory_held(), () -> Native.memory_wanted());\n}}\n",
        library = library.name,
        name = memory_class(library),
    )
}

fn cpp_memory(library: &Library) -> String {
    format!(
        "{HEADER}/**\n\t{MEMORY_DOCS}\n**/\nclass {name} {{\n\tpublic static final meter = new hxn.Gc.Meter(() -> {native}.memory_held(), () -> {native}.memory_wanted());\n}}\n",
        native = native_class(library),
        name = memory_class(library),
    )
}

/// The classes for hxcpp, one file an interface.
pub fn haxe_cpp(library: &Library) -> Vec<File> {
    let mut files: Vec<File> = library
        .interfaces
        .iter()
        .map(|interface| File {
            path: format!("{}.hx", interface.name),
            text: cpp_module(library, interface),
        })
        .collect();
    if library.returns_cells() {
        files.push(File {
            path: format!("{}.hx", cell_class(library)),
            text: cpp_cell(library),
        });
    }
    for interface in library.interfaces.iter().filter(|i| i.shared) {
        files.push(File {
            path: format!("{}.hx", weak_class(&interface.name)),
            text: cpp_weak(library, interface),
        });
    }
    files.extend(later::cpp_files(library));
    files.push(File {
        path: format!("{}.hx", memory_class(library)),
        text: cpp_memory(library),
    });
    files.push(File {
        path: format!("{}.hx", native_class(library)),
        text: cpp_natives(library),
    });
    files
}

// What the extern class calls a handle: a pointer hxcpp does not look into.
const CPP_HANDLE: &str = "Handle";

/// A declaration in the extern class: the glue function `name`.
pub(crate) fn cpp_extern(library: &Library, name: &str, params: &str, returns: &str) -> String {
    format!(
        "\t@:native(\"{}_glue::{name}\") static function {name}({params}):{returns};\n",
        library.name
    )
}

fn cpp_native(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut params = Vec::new();
    if has_receiver(method) {
        params.push(format!("self:{CPP_HANDLE}"));
    }
    for param in &method.params {
        let ty = match &param.ty {
            Type::Bool => String::from("Bool"),
            Type::I32 => String::from("Int"),
            Type::F64 => String::from("Float"),
            Type::Str => String::from("String"),
            Type::Bytes => String::from("haxe.io.BytesData"),
            Type::Handle { .. } => String::from(CPP_HANDLE),
            Type::AtomicInt | Type::AtomicBool => String::from("cpp.RawPointer<Int>"),
            // The wrapper the binding makes, not the function the user passed.
            Type::Lent {
                params: taken,
                returns,
            } => lent::haxe_native_type(taken, returns),
            Type::Void | Type::Future(_) | Type::Stream(_) | Type::Signal(_) => {
                unreachable!("not a parameter type")
            }
        };
        params.push(format!("{}:{ty}", camel(&param.name)));
    }
    let returns = match &method.returns {
        Type::Void => "Void",
        Type::Bool => "Bool",
        Type::I32 => "Int",
        Type::F64 => "Float",
        Type::Str => "String",
        Type::Bytes => "haxe.io.BytesData",
        Type::Lent { .. } => unreachable!("not a result type"),
        // A handle: an object's, a cell's, or a result over time's.
        _ => CPP_HANDLE,
    };
    cpp_extern(
        library,
        &local(&interface.name, &method.name),
        &params.join(", "),
        returns,
    )
}

// The extern class every hxcpp class of the library calls its glue through.
// It is also where the build is told what to include and link.
fn cpp_natives(library: &Library) -> String {
    let upper = library.name.to_uppercase();
    let this = format!("self:{CPP_HANDLE}");
    let mut out = String::from(HEADER);
    // Where the headers and the library are is the build's to say, through
    // defines. hxcpp links its own exceptions under Emscripten but does not
    // compile for them unless told.
    out.push_str(&format!(
        "private typedef Handle = cpp.RawPointer<cpp.Void>;\n\n/** The library's functions, as its glue header declares them. **/\n@:buildXml('\n<files id=\"haxe\">\n\t<compilerflag value=\"-I${{HXN_INCLUDE}}\"/>\n\t<compilerflag value=\"-I${{{upper}_INCLUDE}}\"/>\n</files>\n<section if=\"emscripten\">\n\t<compiler id=\"emscripten\" exe=\"emcc\">\n\t\t<flag value=\"-fexceptions\"/>\n\t</compiler>\n</section>\n<target id=\"haxe\">\n\t<lib name=\"${{{upper}_LIB}}\"/>\n\t<lib name=\"-lpthread\" if=\"linux\"/>\n\t<lib name=\"-ldl\" if=\"linux\"/>\n</target>\n')\n@:include(\"{}_glue.h\")\n@:noCompletion extern class {} {{\n",
        library.name,
        native_class(library)
    ));
    out.push_str(&cpp_extern(library, "release", &this, "Void"));
    out.push_str(&cpp_extern(library, "memory_held", "", "Float"));
    out.push_str(&cpp_extern(library, "memory_wanted", "", "Bool"));
    for interface in &library.interfaces {
        let name = &interface.name;
        for method in &interface.methods {
            out.push_str(&cpp_native(library, interface, method));
        }
        out.push_str(&cpp_extern(library, &local(name, "close"), &this, "Void"));
        if interface.shared {
            let other = format!("{this}, other:{CPP_HANDLE}");
            out.push_str(&cpp_extern(library, &local(name, "same"), &other, "Bool"));
            for method in ["weak", "weak_upgrade"] {
                out.push_str(&cpp_extern(
                    library,
                    &local(name, method),
                    &this,
                    CPP_HANDLE,
                ));
            }
            out.push_str(&cpp_extern(
                library,
                &local(name, "weak_close"),
                &this,
                "Void",
            ));
        }
    }
    if library.returns_cells() {
        out.push_str(&cpp_extern(
            library,
            "atomic_cell",
            &this,
            "cpp.RawPointer<Int>",
        ));
    }
    out.push_str(&later::cpp_natives(library));
    out.push_str("}\n");
    out
}

// The class that owns a cell the library handed over. An `hxn.AtomicInt`
// refers to it, and through it to the memory.
fn cpp_cell(library: &Library) -> String {
    let name = cell_class(library);
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "@:noCompletion class {name} {{\n\t@:unreflective public var raw:cpp.RawPointer<cpp.Void>;\n\n\t// Runs inside a collection: it may free, and may not touch the Haxe heap.\n\tstatic function finalize(self:{name}):Void {{\n\t\t{native}.release(self.raw);\n\t}}\n\n\tpublic static function adopt():{name}\n\t\treturn Type.createEmptyInstance({name});\n\n\tpublic function own():Void\n\t\tcpp.vm.Gc.setFinalizer(this, cpp.Function.fromStaticFunction(finalize));\n\n\t/** The cell, kept alive by this. **/\n\tpublic function cell():hxn.AtomicInt {{\n\t\treturn hxn.AtomicInt.over(cpp.Pointer.fromRaw({native}.atomic_cell(raw)), this);\n\t}}\n}}\n",
        native = native_class(library),
    ));
    out
}
