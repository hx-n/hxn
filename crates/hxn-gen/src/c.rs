//! The C side of the plain-ABI adapter: a header declaring its exports, and
//! the C++ glue hxcpp calls them through.

use crate::later;
use crate::lent;
use crate::model::{Interface, Library, Method, Type};
use crate::names::{
    cell_export, export, has_receiver, held_export, local, release, thrown_export, wanted_export,
};

const HEADER: &str = "/* Generated by hxn-gen from the library's source. Do not edit. */\n";

fn guard_name(library: &Library, suffix: &str) -> String {
    format!("{}_{suffix}_H", library.name.to_uppercase())
}

fn declaration(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut params = Vec::new();
    if has_receiver(method) {
        params.push(String::from("hxn_handle *self"));
    }
    for param in &method.params {
        let ty = match &param.ty {
            Type::Bool | Type::I32 => "int32_t ",
            Type::I64 => "int64_t ",
            Type::F64 => "double ",
            Type::Str | Type::Bytes => "hxn_slice ",
            Type::BytesMut => "hxn_slice_mut ",
            Type::Handle { .. } => "hxn_handle *",
            Type::AtomicInt | Type::AtomicBool => "int32_t *",
            // Borrowed for the call, so its `drop` is null.
            Type::Lent { .. } => "hxn_callback ",
            Type::Void
            | Type::Future(_)
            | Type::Stream(_)
            | Type::Signal(_)
            | Type::List { .. }
            | Type::Data(_) => {
                unreachable!("not a parameter type")
            }
        };
        params.push(format!("{ty}{}", param.name));
    }
    match &method.returns {
        Type::Void => {}
        Type::Bool | Type::I32 => params.push(String::from("int32_t *out")),
        Type::I64 => params.push(String::from("int64_t *out")),
        Type::F64 => params.push(String::from("double *out")),
        Type::Str | Type::Bytes => params.push(String::from("hxn_buf *out")),
        Type::Lent { .. } | Type::List { .. } | Type::Data(_) | Type::BytesMut => {
            unreachable!("not a result type")
        }
        Type::Handle { .. }
        | Type::AtomicInt
        | Type::AtomicBool
        | Type::Future(_)
        | Type::Stream(_)
        | Type::Signal(_) => {
            params.push(String::from("hxn_handle **out"));
        }
    }
    params.push(String::from("hxn_buf *err"));
    format!(
        "hxn_status {}({});\n",
        export(library, &interface.name, &method.name),
        params.join(", ")
    )
}

/// `<library>_abi.h`: declarations of the plain-ABI adapter's exports.
pub fn c_header(library: &Library) -> String {
    let guard = guard_name(library, "ABI");
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "#ifndef {guard}\n#define {guard}\n\n#include \"hxn.h\"\n\n"
    ));
    out.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
    for interface in &library.interfaces {
        out.push_str(&format!("\n/* {} */\n", interface.name));
        for method in &interface.methods {
            out.push_str(&declaration(library, interface, method));
        }
        if interface.namespace {
            continue;
        }
        out.push_str(&format!(
            "hxn_status {}(hxn_handle *self, hxn_buf *err);\n",
            export(library, &interface.name, "close")
        ));
        if interface.shared {
            let name = &interface.name;
            out.push_str(&format!(
                "/* Whether two handles hold one value, and a weak reference to it: a handle\n * of its own, upgraded to a new handle of the value or to null. */\nhxn_status {same}(hxn_handle *self, hxn_handle *other, int32_t *out, hxn_buf *err);\nhxn_status {weak}(hxn_handle *self, hxn_handle **out, hxn_buf *err);\nhxn_status {upgrade}(hxn_handle *self, hxn_handle **out, hxn_buf *err);\nhxn_status {close}(hxn_handle *self, hxn_buf *err);\n",
                same = export(library, name, "same"),
                weak = export(library, name, "weak"),
                upgrade = export(library, name, "weak_upgrade"),
                close = export(library, name, "weak_close"),
            ));
        }
    }
    if library.returns_cells() {
        out.push_str(&format!(
            "\n/* Where a cell the library handed over is: an int for the host's own atomic\n * operations, alive as long as the handle. */\nhxn_status {}(hxn_handle *self, int32_t **out, hxn_buf *err);\n",
            cell_export(library)
        ));
    }
    out.push_str(&later::c_header(library));
    if !library.errors().is_empty() {
        out.push_str(&format!(
            "\n/* The value of the failure this thread just met, where the library failed with\n * data of its own: 1 and the bytes, which start with which error it is, or 0. */\nint32_t {}(hxn_buf *out);\n",
            thrown_export(library)
        ));
    }
    out.push_str(&format!(
        "\n/* The bytes the library's values hold that the host's collector cannot see,\n * and whether the library asked for a collection since the last call. */\ndouble {}(void);\nint32_t {}(void);\n",
        held_export(library),
        wanted_export(library)
    ));
    out.push_str(&format!(
        "\n/* Frees a handle of any interface. Called by a finalizer, and by nothing else. */\nvoid {}(hxn_handle *self);\n",
        release(library)
    ));
    out.push_str("\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n");
    out
}

fn glue(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut params = Vec::new();
    let mut arguments = Vec::new();
    let mut locals = Vec::new();
    if has_receiver(method) {
        params.push(String::from("void *self"));
        arguments.push(String::from("(hxn_handle *)self"));
    }
    for param in &method.params {
        let name = &param.name;
        match &param.ty {
            Type::Bool => {
                params.push(format!("bool {name}"));
                arguments.push(format!("{name} ? 1 : 0"));
            }
            Type::I32 => {
                params.push(format!("int {name}"));
                arguments.push(name.clone());
            }
            Type::I64 => {
                params.push(format!("cpp::Int64 {name}"));
                arguments.push(name.clone());
            }
            Type::F64 => {
                params.push(format!("double {name}"));
                arguments.push(name.clone());
            }
            Type::Str => {
                params.push(format!("::String {name}"));
                locals.push(format!("hx::strbuf {name}_storage;"));
                arguments.push(format!("hxn::slice({name}, {name}_storage)"));
            }
            Type::Bytes => {
                params.push(format!("Array<unsigned char> {name}"));
                arguments.push(format!("hxn::slice({name})"));
            }
            Type::BytesMut => {
                params.push(format!("Array<unsigned char> {name}"));
                arguments.push(format!("hxn::slice_mut({name})"));
            }
            Type::Handle { .. } => {
                params.push(format!("void *{name}"));
                arguments.push(format!("(hxn_handle *){name}"));
            }
            Type::AtomicInt | Type::AtomicBool => {
                params.push(format!("int *{name}"));
                arguments.push(name.clone());
            }
            Type::Lent {
                params: taken,
                returns,
            } => {
                params.push(format!("Dynamic {name}"));
                // On this stack frame for the call, so the library drops
                // nothing.
                locals.push(format!(
                    "hxn_callback {name}_lent = {{ (void *){}, {name}.mPtr, 0 }};",
                    lent::trampoline(taken, returns)
                ));
                arguments.push(format!("{name}_lent"));
            }
            Type::Void
            | Type::Future(_)
            | Type::Stream(_)
            | Type::Signal(_)
            | Type::List { .. }
            | Type::Data(_) => {
                unreachable!("not a parameter type")
            }
        }
    }
    let (returns, out, result) = match &method.returns {
        Type::Void => ("void", None, None),
        Type::Bool => ("bool", Some("int out = 0;"), Some("out != 0")),
        Type::I32 => ("int", Some("int out = 0;"), Some("out")),
        Type::I64 => ("cpp::Int64", Some("int64_t out = 0;"), Some("out")),
        Type::F64 => ("double", Some("double out = 0;"), Some("out")),
        Type::Str => (
            "::String",
            Some("hxn_buf out = HXN_BUF_EMPTY;"),
            Some("hxn::take_string(out)"),
        ),
        Type::Lent { .. } | Type::List { .. } | Type::Data(_) | Type::BytesMut => {
            unreachable!("not a result type")
        }
        Type::Bytes => (
            "Array<unsigned char>",
            Some("hxn_buf out = HXN_BUF_EMPTY;"),
            Some("hxn::take_bytes(out)"),
        ),
        Type::Handle { .. }
        | Type::AtomicInt
        | Type::AtomicBool
        | Type::Future(_)
        | Type::Stream(_)
        | Type::Signal(_) => ("void *", Some("hxn_handle *out = 0;"), Some("out")),
    };
    if let Some(out) = out {
        locals.push(String::from(out));
        arguments.push(String::from("&out"));
    }
    locals.push(String::from("hxn_buf err = HXN_BUF_EMPTY;"));
    arguments.push(String::from("&err"));
    let call = format!(
        "{}({})",
        export(library, &interface.name, &method.name),
        arguments.join(", ")
    );
    let mut body = String::new();
    for local in &locals {
        body.push_str(&format!("\t{local}\n"));
    }
    if method.blocking {
        // The garbage collector may run while this thread blocks; the
        // blocking zone ends before any exception is thrown.
        body.push_str(&format!(
            "\thxn_status status;\n\t{{\n\t\thxn::Blocking zone;\n\t\tstatus = {call};\n\t}}\n\thxn::check(status, err);\n"
        ));
    } else {
        body.push_str(&format!("\thxn::check({call}, err);\n"));
    }
    if let Some(result) = result {
        body.push_str(&format!("\treturn {result};\n"));
    }
    let separator = if returns.ends_with('*') { "" } else { " " };
    format!(
        "inline {returns}{separator}{}({}) {{\n{body}}}\n",
        local(&interface.name, &method.name),
        params.join(", ")
    )
}

/// `<library>_glue.h`: the functions hxcpp calls. Each one frees what the
/// library returned to it, and throws a failure only after the library call
/// has returned.
pub fn cpp_glue(library: &Library) -> String {
    let guard = guard_name(library, "GLUE");
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "#ifndef {guard}\n#define {guard}\n\n#include \"{}_abi.h\"\n\nnamespace {}_glue {{\n",
        library.name, library.name
    ));
    out.push_str(&lent::cpp_trampolines(library));
    out.push_str(&format!(
        "\n// What a finalizer calls: it frees, and touches nothing of the runtime's.\ninline void release(void *self) {{\n\t{release}((hxn_handle *)self);\n}}\n\ninline double memory_held() {{\n\treturn {held}();\n}}\n\ninline bool memory_wanted() {{\n\treturn {wanted}() != 0;\n}}\n",
        release = release(library),
        held = held_export(library),
        wanted = wanted_export(library),
    ));
    for interface in &library.interfaces {
        for method in &interface.methods {
            out.push('\n');
            out.push_str(&glue(library, interface, method));
        }
        if interface.namespace {
            continue;
        }
        out.push_str(&format!(
            "\ninline void {}(void *self) {{\n\thxn_buf err = HXN_BUF_EMPTY;\n\thxn::check({}((hxn_handle *)self, &err), err);\n}}\n",
            local(&interface.name, "close"),
            export(library, &interface.name, "close")
        ));
        if interface.shared {
            let name = &interface.name;
            out.push_str(&format!(
                "\ninline bool {same}(void *self, void *other) {{\n\tint out = 0;\n\thxn_buf err = HXN_BUF_EMPTY;\n\thxn::check({same_export}((hxn_handle *)self, (hxn_handle *)other, &out, &err), err);\n\treturn out != 0;\n}}\n",
                same = local(name, "same"),
                same_export = export(library, name, "same"),
            ));
            for method in ["weak", "weak_upgrade"] {
                out.push_str(&format!(
                    "\ninline void *{}(void *self) {{\n\thxn_handle *out = 0;\n\thxn_buf err = HXN_BUF_EMPTY;\n\thxn::check({}((hxn_handle *)self, &out, &err), err);\n\treturn out;\n}}\n",
                    local(name, method),
                    export(library, name, method)
                ));
            }
            out.push_str(&format!(
                "\ninline void {}(void *self) {{\n\thxn_buf err = HXN_BUF_EMPTY;\n\thxn::check({}((hxn_handle *)self, &err), err);\n}}\n",
                local(name, "weak_close"),
                export(library, name, "weak_close")
            ));
        }
    }
    if library.returns_cells() {
        out.push_str(&format!(
            "\ninline int *atomic_cell(void *self) {{\n\tint32_t *out = 0;\n\thxn_buf err = HXN_BUF_EMPTY;\n\thxn::check({}((hxn_handle *)self, &out, &err), err);\n\treturn out;\n}}\n",
            cell_export(library)
        ));
    }
    out.push_str(&later::cpp_glue(library));
    if !library.errors().is_empty() {
        out.push_str(&format!(
            "\n// Null when the failure just met had no value of its own.\ninline Array<unsigned char> thrown_take() {{\n\thxn_buf out = HXN_BUF_EMPTY;\n\tif (!{}(&out))\n\t\treturn null();\n\treturn hxn::take_bytes(out);\n}}\n",
            thrown_export(library)
        ));
    }
    out.push_str("\n}\n\n#endif\n");
    out
}
