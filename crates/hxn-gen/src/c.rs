//! The C side of the plain-ABI adapter: a header declaring its exports, and
//! the C++ glue hxcpp calls them through.

use crate::model::{Interface, Library, Method, Type};
use crate::names::{export, has_receiver, local, release};

const HEADER: &str = "/* Generated by hxn-gen from the library's source. Do not edit. */\n";

fn guard_name(library: &Library, suffix: &str) -> String {
    format!("{}_{suffix}_H", library.name.to_uppercase())
}

fn declaration(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut params = Vec::new();
    if has_receiver(method) {
        params.push(String::from("hxn_handle *self"));
    }
    for param in &method.params {
        let ty = match param.ty {
            Type::Bool | Type::I32 => "int32_t",
            Type::F64 => "double",
            Type::Str | Type::Bytes => "hxn_slice",
            Type::Void | Type::Own => unreachable!("not a parameter type"),
        };
        params.push(format!("{ty} {}", param.name));
    }
    match method.returns {
        Type::Void => {}
        Type::Bool | Type::I32 => params.push(String::from("int32_t *out")),
        Type::F64 => params.push(String::from("double *out")),
        Type::Str => params.push(String::from("hxn_buf *out")),
        Type::Own => params.push(String::from("hxn_handle **out")),
        Type::Bytes => unreachable!("not a result type"),
    }
    params.push(String::from("hxn_buf *err"));
    format!(
        "hxn_status {}({});\n",
        export(library, interface, &method.name),
        params.join(", ")
    )
}

/// `<library>_abi.h`: what the plain-ABI adapter exports.
pub fn c_header(library: &Library) -> String {
    let guard = guard_name(library, "ABI");
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "#ifndef {guard}\n#define {guard}\n\n#include \"hxn.h\"\n\n"
    ));
    out.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
    for interface in &library.interfaces {
        out.push_str(&format!("\n/* {} */\n", interface.name));
        for method in &interface.methods {
            out.push_str(&declaration(library, interface, method));
        }
        out.push_str(&format!(
            "hxn_status {}(hxn_handle *self, hxn_buf *err);\n",
            export(library, interface, "close")
        ));
    }
    out.push_str(&format!(
        "\n/* Frees a handle of any interface. Called by a finalizer, and by nothing else. */\nvoid {}(hxn_handle *self);\n",
        release(library)
    ));
    out.push_str("\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n");
    out
}

fn glue(library: &Library, interface: &Interface, method: &Method) -> String {
    let mut params = Vec::new();
    let mut arguments = Vec::new();
    let mut locals = Vec::new();
    if has_receiver(method) {
        params.push(String::from("void *self"));
        arguments.push(String::from("(hxn_handle *)self"));
    }
    for param in &method.params {
        let name = &param.name;
        match param.ty {
            Type::Bool => {
                params.push(format!("bool {name}"));
                arguments.push(format!("{name} ? 1 : 0"));
            }
            Type::I32 => {
                params.push(format!("int {name}"));
                arguments.push(name.clone());
            }
            Type::F64 => {
                params.push(format!("double {name}"));
                arguments.push(name.clone());
            }
            Type::Str => {
                params.push(format!("::String {name}"));
                locals.push(format!("hx::strbuf {name}_storage;"));
                arguments.push(format!("hxn::slice({name}, {name}_storage)"));
            }
            Type::Bytes => {
                params.push(format!("Array<unsigned char> {name}"));
                arguments.push(format!("hxn::slice({name})"));
            }
            Type::Void | Type::Own => unreachable!("not a parameter type"),
        }
    }
    let (returns, out, result) = match method.returns {
        Type::Void => ("void", None, None),
        Type::Bool => ("bool", Some("int out = 0;"), Some("out != 0")),
        Type::I32 => ("int", Some("int out = 0;"), Some("out")),
        Type::F64 => ("double", Some("double out = 0;"), Some("out")),
        Type::Str => (
            "::String",
            Some("hxn_buf out = HXN_BUF_EMPTY;"),
            Some("hxn::take_string(out)"),
        ),
        Type::Own => ("void *", Some("hxn_handle *out = 0;"), Some("out")),
        Type::Bytes => unreachable!("not a result type"),
    };
    if let Some(out) = out {
        locals.push(String::from(out));
        arguments.push(String::from("&out"));
    }
    locals.push(String::from("hxn_buf err = HXN_BUF_EMPTY;"));
    arguments.push(String::from("&err"));
    let call = format!(
        "{}({})",
        export(library, interface, &method.name),
        arguments.join(", ")
    );
    let mut body = String::new();
    for local in &locals {
        body.push_str(&format!("\t{local}\n"));
    }
    if method.blocking {
        // The collector may run while this thread waits; the zone ends
        // before anything is thrown.
        body.push_str(&format!(
            "\thxn_status status;\n\t{{\n\t\thxn::Blocking zone;\n\t\tstatus = {call};\n\t}}\n\thxn::check(status, err);\n"
        ));
    } else {
        body.push_str(&format!("\thxn::check({call}, err);\n"));
    }
    if let Some(result) = result {
        body.push_str(&format!("\treturn {result};\n"));
    }
    let separator = if returns.ends_with('*') { "" } else { " " };
    format!(
        "inline {returns}{separator}{}({}) {{\n{body}}}\n",
        local(interface, &method.name),
        params.join(", ")
    )
}

/// `<library>_glue.h`: what hxcpp calls. Each function returns before its
/// failure is thrown, and frees what the library handed it.
pub fn cpp_glue(library: &Library) -> String {
    let guard = guard_name(library, "GLUE");
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "#ifndef {guard}\n#define {guard}\n\n#include \"{}_abi.h\"\n\nnamespace {}_glue {{\n",
        library.name, library.name
    ));
    for interface in &library.interfaces {
        for method in &interface.methods {
            out.push('\n');
            out.push_str(&glue(library, interface, method));
        }
        out.push_str(&format!(
            "\ninline void {}(void *self) {{\n\thxn_buf err = HXN_BUF_EMPTY;\n\thxn::check({}((hxn_handle *)self, &err), err);\n}}\n",
            local(interface, "close"),
            export(library, interface, "close")
        ));
    }
    out.push_str("\n}\n\n#endif\n");
    out
}
